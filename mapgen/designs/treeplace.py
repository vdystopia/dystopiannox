        sq_ = [(int(math.floor(a)), int(math.floor(b_)) + 1) for a, b_ in spots]
        if all(q in land.squares and q not in land.taken_strict and q not in land.water for q in sq_):
            for a, b_ in spots: torch_pole(a, b_)
