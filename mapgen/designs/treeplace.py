"""TreePlace: a sacred mana forest (generator v3, built with PROCESS.md from the centre outwards).

A giant cluster of mana crystals glows in the heart of a silver grove, ringed by standing stones.
Three forests with their own character stretch out from it:
- north, the Grovelord's Wood: ancient green forest, where the grovelord lives in a large shack;
- west, the Golden Wood: aspens and autumn trees, a lily pond;
- south, the Pine Wood: pines and ferns, a brook crossed by a rope bridge.
A long winding path leaves the grove eastwards to a mana mine's mining camp: a bunkhouse, a mess hall,
the foreman's house and an ore shed around a work yard, beneath a rock cliff whose mine mouth is
blocked with boulders (the mines are not accessible). The traveller arrives at the camp's road.

Single player (Solo), one PlayerStart, no .nxz.
    py mapgen/designs/treeplace.py [out_dir|-] [seed]
"""
