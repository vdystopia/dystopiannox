land.reserve_band([POND[0], (POND[0][0] + 0.1, POND[0][1])], POND[1] * 1.35 + 2)

# ---- 2. the centre: the heart grove's crystal circle and the ring path the trails arrive at -----------------
hc = land.areas["heart"]["c"]
RING_IN, RING_OUT = 7.0, 8.6
inner = {(i, j) for i in range(int(hc[0]) - 12, int(hc[0]) + 13) for j in range(int(hc[1]) - 11, int(hc[1]) + 14)
         if math.hypot(i + 0.5 - hc[0], j - 0.5 - hc[1]) < RING_IN}
