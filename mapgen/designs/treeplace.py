def light(si, sj, xfer, dz=-5):
    x, y = square_px(si, sj)
    m.obj_px("ColorLight", x, y + dz, xfer=dict(xfer))


def torch_pole(si, sj):
    s = (int(si), int(sj) + 1)
    if s not in land.squares or s in land.water or s in land.taken_strict: return False
    x, y = square_px(si, sj)
    m.obj_px("TorchPole", x, y)
    m.obj_px("ColorLight", x, y - 5, xfer=dict(ORANGE))
    land.taken.add(s)
    return True


