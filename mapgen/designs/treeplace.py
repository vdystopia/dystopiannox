land.paint_roads(m, "DirtDark2", skip=land.reserved | inner)
for s in ring:
    m.floor[square_tile(*s)] = "DirtDark2"
    land.roads.add(s)

# the camp's work yard comes first in the east, and with it the mine: a rock face along the yard's
# north-west side (the side the loop of the winding path encloses), the mouth facing the yard
cc = land.areas["camp"]["c"]
land.paint_square(m, "camp", 11, "DirtHard")
