# ---- 3. buildings: the camp's buildings face the yard; the grovelord's shack faces his trail -----------------
placed, door_paths = [], set()
for k, bid in enumerate(ID.buildings):
    role = BUILDINGS[bid.role]
    size = role["size"]
    program = [kind for kind, _ in role["rooms"]]
    lots = land.square_lots(size) if role["faces"] == "square" else []
    lots += land.lots(bid.area, size)
    if bid.role == "ore_shed":                                    # ore comes out of the mine into the shed
        mo = mine.mouth
        lots.sort(key=lambda lt: math.hypot(lt[0][0] / 2 + size[0] / 4 - mo[0], lt[0][1] / 2 + size[1] / 4 - mo[1]))
    b = None
    for origin, side in lots:
        if not land.lot_free(origin, size, margin=1): continue
        b = generate_building(m, rng, origin, size, role["style"], program=program, entrance_side=side,
                              building_id=f"B{k}", occupied={square_tile(*s) for s in land.taken}, tries=12,
                              shape=role.get("shape"), min_units=role.get("min_units", 0))
        if b: break
    if not b:
        print(f"could not place the {bid.role} in the {bid.area}"); continue
    land.take_cells(b.cells, margin=1)
    land.taken_strict |= _squares_of(b.footprint)
    land.wall_cells |= set(m.wallmap)
    placed.append((bid, b))

# ---- 4. the outlying features' footprints: obelisks around the grove, the fairy ring --------------------------
trail_angles = sorted(math.atan2(land.areas[x]["c"][1] - hc[1], land.areas[x]["c"][0] - hc[0])
                      for x in ("grovelord", "west_pond", "south_glade", "p1"))
obelisks = []
for k, a0 in enumerate(trail_angles):
    a1 = trail_angles[(k + 1) % len(trail_angles)] + (2 * math.pi if k == len(trail_angles) - 1 else 0)
    gap = a1 - a0
    n = max(1, round(gap / (2 * math.pi / 8)))
    for q in range(n):
        a = a0 + gap * (q + 1) / (n + 1)
        obelisks.append((hc[0] + 10.6 * math.cos(a), hc[1] + 10.6 * math.sin(a)))
for si, sj in obelisks:
    land.taken |= {(int(si) + a, int(sj) + 1 + b) for a in (-1, 0, 1) for b in (-1, 0, 1)}
ne = land.areas["north_e"]["c"]
land.taken |= {(int(ne[0]) + a, int(ne[1]) + 1 + b) for a in (-2, -1, 0, 1, 2) for b in (-2, -1, 0, 1, 2)}

