"""TrapDemo 08: The Storm Anvil (map TrapDem08; kit/trapdemo.py Mission). A smiths' guild forge in the hills, taken by
a spellsword.

The story
- The hook: Dudley, the smith's lad, got out of the forge with a cut arm and has made camp at its gate. Dravik
  Stormblade, a spellsword with a band of fire demons, killed his master and took the forge; he wants the storm
  anvil's heart, the stone that lets the anvil make blades that call lightning. The guild built the forge's machines
  to guard the anvil: fire jets, pushers, presses and blades, and they are still running.
- Main quest (the anvil's heart): get down through the forge, put down Dravik in his forge-hall (the old smithy) and
  bring the heart from the vault behind it back to Dudley, who pays.
- Side quest (the master's tongs): the master's tool bag, with his tongs in it, lies in the slag store behind the
  engine room's pusher passage. Dudley gives fire potions and a little gold for it.
- The traps, in the order a player meets them (each kind taught standard before its hard form): flame jets on a
  clock at the gate (where a mistake is cheap, the camp's potions behind); the pushers on the beat from the engine
  room (the winches that work the guild's machines) to the slag store (the side quest's price, a dead end); the
  snapping jaws, the forge's presses, to the workshop; the blades in the wall to the powder store; then, after the
  middle, find the gap to the guild's great hall and the skulls and fire into Dravik's forge-hall.

    py mapgen/designs/trapdemo08.py [out_dir|-]
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from kit.trapdemo import Mission
from kit.quests import A
from kit.trapdemo_dress import camp, clear_mouths, start_spot, free_spot, extra

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "TrapDem08"
M = Mission(NAME, "The Storm Anvil", "forge", seed=8,
            description="[env:castle] TrapDemo 08, The Storm Anvil: a smiths' guild forge whose machines still guard "
                        "the storm anvil; a spellsword and his fire demons hold it. Generated by Claude.")
M.room("camp", (14, 12), role="camp", start=True)
M.room("gate", (14, 12), role="guard", kind="guardroom")
M.room("engine", (16, 14), role="room", kind="winch_room")
M.room("slag", (12, 12), role="store", kind="storeroom")
M.room("workshop", (16, 14), role="room", kind="workshop")
M.room("powder", (14, 12), role="store", kind="powder_store")
M.room("greathall", (18, 16), role="room", kind="great_hall")
M.room("forge", (18, 16), role="boss", kind="smithy")
M.room("vault", (12, 12), role="vault", kind="treasury")
M.link("camp", "gate", trap=("flame", 0))                    # flame jets on a clock: the way in
M.link("gate", "engine", length=6)
M.link("engine", "slag", trap=("push", 0))                  # pushers on the beat: the side quest's price
M.link("engine", "workshop", trap=("block", 1))             # snapping jaws: the presses
M.link("workshop", "powder", trap=("blade", 1))              # the jaws: blades in the wall
M.link("powder", "greathall", trap=("blade", 6))             # find the gap (hard)
M.link("greathall", "forge", trap=("flame", 7))              # skulls and fire (hard): into Dravik's forge-hall
M.link("forge", "vault", length=5)
M.layout()
n0 = len(M.m.d["objects"])
M.dress()
clear_mouths(M, M.m.d["objects"][n0:])     # nothing of the dressing in a passage's mouth


def sign_spot(rid):
    """A room point for the camp's sign: beside the way on (the first passage's mouth), a square into the room and
    four along the wall from the mouth's middle, off every piece."""
    w, h = M.rooms[rid]["size"]
    da, db = M.doors[rid][0]
    n = (0, 1) if db < 1 else (0, -1) if db > h - 1 else (1, 0) if da < 1 else (-1, 0)     # into the room
    t = (n[1], n[0])
    along = da if n[0] == 0 else db
    side = -1 if along - 4.2 > 1.2 else 1
    return free_spot(M, rid, da + n[0] * 1.1 + t[0] * 4.2 * side, db + n[1] * 1.1 + t[1] * 4.2 * side, clear=0.9)


camp(M, "camp")                                  # the lived-in camp (kit/trapdemo_dress.py)
# the lad's own corner of the forge camp: his anvil, tools and a crate of apples by the north-east wall
extra(M, "camp", [("Anvil1", 7.0, 10.8), ("BarrelWithTools1", 9.2, 10.9), ("TraderAppleCrate", 5.0, 10.9)])
sign_at = sign_spot("camp")
M.start_at("camp", *start_spot(M, "camp"))

# ---- life -------------------------------------------------------------------------------------------------------
M.monsters("gate", {"Imp": 3})
M.monsters("engine", {"FireSprite": 2, "Imp": 2})
M.monsters("slag", {"Imp": 2, "FireSprite": 1})
M.monsters("workshop", {"EmberDemon": 1, "Imp": 2})
M.monsters("powder", {"EmberDemon": 2})
M.monsters("greathall", {"MeleeDemon": 1, "EmberDemon": 2, "FireSprite": 1})
M.monsters("forge", {"FireSprite": 2})
boss = M.boss("forge", "B7")
extra(M, "vault", [("Anvil1", 6.0, 7.4)], reach=1.5)            # the storm anvil's own stand, the heart before it
heart = M.item("vault", "BlueOrb", *free_spot(M, "vault", 6.0, 6.0, clear=0.8))
bag = M.item("slag", "TreasureBag", *free_spot(M, "slag", 4.0, 4.0))
# potions where a player stops between stages: the slag store's dead end, the powder store before the hard halls
for rid, n in (("slag", 1), ("powder", 2), ("greathall", 1)):
    pa, pb = free_spot(M, rid, 2.0, 2.0, clear=1.2)
    for k in range(n):
        M.put(rid, "RedPotion", pa + 0.45 * k, pb, clear=2.4)
dudley = M.person("camp", "Con03B", "Dudley", "Dudley", pic="WoundedApprenticePic", title="Dudley")

# ---- the story --------------------------------------------------------------------------------------------------
q = M.q
MAIN, SIDE = "anvil", "tongs"
GOAL = "Bring the storm anvil's heart back from Dravik's forge."
ERRAND = "Find the master's tool bag in the slag store."
q.talker(dudley, [
    q.say("Thanks again, brave Adventurer. The forge will ring again, I promise you that.",
          when=q.at(MAIN, 3)),
    q.say("The storm anvil's heart! You really brought it out! My master would have shaken your hand. Here's your "
          "reward, as I promised. Take it!",
          when=q.at(MAIN, 2, has="BlueOrb"),
          do=[A.take("BlueOrb"), A.gold(500), A.give("RedPotion", 2), A.stage(MAIN, 3), q.done(GOAL)]),
    q.say("You have the heart already? Then Dravik still lives down there. Finish him first, or he'll come after it.",
          when=q.at(MAIN, 1, has="BlueOrb")),
    q.say("My master's tongs! Thank goodness! Now I can work the anvil again. Please, take these. They keep the fire "
          "off you.",
          when=q.when(has="TreasureBag", not_=f"{SIDE}done"),
          do=[A.take("TreasureBag"), A.give("FireProtectPotion", 2), A.gold(150), A.flag(f"{SIDE}done"),
              q.done(ERRAND)]),
    q.say("Dravik is dead?! Then hurry! The heart is in the vault behind his hall.",
          when=q.at(MAIN, 2)),
    q.say("Why are you still here? Every day he has that anvil, he grows stronger!",
          when=q.at(MAIN, 1)),
    q.say("Ow! Mind my arm, it's cut to the bone!\n\n"
          "A spellsword called Dravik Stormblade came up the road with a band of fire demons. He killed my master and "
          "took the forge for himself. He wants the storm anvil's heart, to make blades that call down lightning!\n\n"
          "The heart is kept in the vault past the big forge-hall, deep inside. The guild's old machines still guard "
          "the way. Will you go in and bring it back? I'll see you're paid for it.",
          when=q.at(MAIN, 0), ask=True,
          do=[A.stage(MAIN, 1), q.journal(GOAL), q.journal(ERRAND),
              q.tell(dudley, "Oh, and the slag store, off the engine room. My master's tool bag is in there, with "
                             "his tongs. I'd like them back, if you can.")],
          else_=[q.tell(dudley, "Then go. I'll keep the fire lit and hope he doesn't come up the road.")]),
], pic="WoundedApprenticePic", title="Dudley")
q.on_death(boss, [A.stage(MAIN, 2), q.journal("Take the anvil's heart from the vault and return to Dudley.")])
q.start([q.journal("Speak to Dudley at the camp by the forge gate.")])
M.sign("camp", "THE STORM ANVIL. Guild smiths only past this gate.", *sign_at)

m = M.m                                   # tests/server_smoke.py reads the spec as m
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out", "trapdemo", NAME)
M.finish(None if out == "-" else out)
