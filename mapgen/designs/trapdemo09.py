"""TrapDemo 09: The Sunken Sanctum (map TrapDem09; kit/trapdemo.py Mission). A temple of the sun on a lake shore, its
lower halls half drowned since the lake rose.

The story
- The hook: Father Morgan, a priest of the temple, keeps a camp on the temple steps with what pilgrims stayed. Kesh of
  the Red Sands, a raider from the southern deserts, broke into the sanctum with his scorpions for the sun disk, the
  temple's holiest relic; spiders have bred in the wet halls since the water came in. The old priests warded the way
  down: arrows in the walls, beams of light, false floors and plates.
- Main quest (the sun disk): get down through the temple, put down Kesh in the drowned sanctum and bring the disk
  from the vault behind it back to Morgan, who pays and blesses.
- Side quest (the prayer book): the acolyte Edwin dropped his prayer book in the cistern when the scorpions came; the
  cistern hangs off the chapel behind a passage of false floors. Morgan gives cure-poison potions for it (the
  spiders' bite).
- The traps, in the order a player meets them (each kind taught standard before its hard form): lane plates and
  arrows at the way in (a cheap mistake, the camp's potions behind); look before you leap, a pit passage to the
  cistern (the side quest's price, a dead end); one beam on a clock to the scriptorium; race the gate to the sun
  shrine; then, after the middle, crossing beams to the high priests' tombs and the lane hall's arrows into the
  sanctum.

    py mapgen/designs/trapdemo09.py [out_dir|-]
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from kit.trapdemo import Mission
from kit.quests import A
from kit.trapdemo_dress import camp, clear_mouths, start_spot, free_spot, extra

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "TrapDem09"
M = Mission(NAME, "The Sunken Sanctum", "temple", seed=9,
            description="[env:castle] TrapDemo 09, The Sunken Sanctum: a half-drowned temple of the sun whose old "
                        "wards still guard its relic; a desert raider and his scorpions went down for it. "
                        "Generated by Claude.")
M.room("camp", (14, 12), role="camp", start=True)
M.room("narthex", (16, 12), role="room", kind="gallery")
M.room("chapel", (16, 14), role="room", kind="chapel")
M.room("cistern", (12, 12), role="store", kind="conservatory")
M.room("library", (16, 14), role="room", kind="library")
M.room("sunroom", (14, 14), role="shrine", kind="shrine")
M.room("tombs", (14, 12), role="crypt", kind="crypt")
M.room("sanctum", (18, 16), role="boss", kind="hall")
M.room("vault", (12, 12), role="vault", kind="treasury")
M.link("camp", "narthex", trap=("arrow", 0))                 # lane plates: the way in
M.link("narthex", "chapel", length=6)
M.link("chapel", "cistern", trap=("pit", 2))                 # look before you leap: the side quest's price
M.link("chapel", "library", trap=("sentry", 0))              # one beam on a clock
M.link("library", "sunroom", trap=("trigger", 5))            # race the gate
M.link("sunroom", "tombs", trap=("sentry", 5))               # crossing beams (hard)
M.link("tombs", "sanctum", trap=("arrow", 5))                # the lane hall (hard): into the sanctum
M.link("sanctum", "vault", length=5)
M.layout()
n0 = len(M.m.d["objects"])
M.dress()
clear_mouths(M, M.m.d["objects"][n0:])     # nothing of the dressing in a passage's mouth
# the sun shrine: round the furnisher's altar on the north-east wall, the sun's court (its ways in cross the room from
# the north-west wall to the south-east one, along its middle)
for t, a, b in (("Statue2g", 4.4, 12.6), ("Statue2g", 9.6, 12.6), ("Brazier", 5.6, 10.8), ("Brazier", 8.4, 10.8),
                ("Column6", 3.6, 9.8), ("Column6", 10.4, 9.8), ("Column6", 3.6, 4.2), ("Column6", 10.4, 4.2),
                ("Candleabra3", 5.8, 2.0), ("Candleabra3", 8.2, 2.0), ("Statue2c", 7.0, 1.4),
                ("Plant4", 1.2, 1.3), ("PlantFern1", 12.8, 1.3), ("Mushroom4", 1.4, 12.6), ("PlantFern1", 12.6, 12.6)):
    M.put("sunroom", t, a, b, clear=3.2)


def sign_spot(rid):
    """A room point for the camp's sign: beside the way on (the first passage's mouth), a square into the room and
    four along the wall from the mouth's middle, off every piece."""
    w, h = M.rooms[rid]["size"]
    da, db = M.doors[rid][0]
    n = (0, 1) if db < 1 else (0, -1) if db > h - 1 else (1, 0) if da < 1 else (-1, 0)     # into the room
    t = (n[1], n[0])
    along = da if n[0] == 0 else db
    side = -1 if along - 4.2 > 1.2 else 1
    return free_spot(M, rid, da + n[0] * 1.1 + t[0] * 4.2 * side, db + n[1] * 1.1 + t[1] * 4.2 * side, clear=0.9)


camp(M, "camp")                                  # the lived-in camp (kit/trapdemo_dress.py)
# the pilgrims' camp: a little altar of candles by the north-east wall, a crate of offerings and a water cask
extra(M, "camp", [("Candleabra2", 7.0, 10.9), ("TraderAppleCrate", 5.0, 10.9), ("WaterBarrel", 9.2, 10.9)])
sign_at = sign_spot("camp")
M.start_at("camp", *start_spot(M, "camp"))

# ---- life -------------------------------------------------------------------------------------------------------
M.monsters("narthex", {"Spider": 2, "Urchin": 2})
M.monsters("chapel", {"Spider": 2, "SpittingSpider": 1})
M.monsters("cistern", {"Spider": 2, "SpittingSpider": 1})
M.monsters("library", {"SpittingSpider": 2, "Scorpion": 1})
M.monsters("sunroom", {"Scorpion": 2, "BlackWidow": 1})
M.monsters("tombs", {"Scorpion": 2, "BlackWidow": 1, "SpittingSpider": 1})
M.monsters("sanctum", {"Scorpion": 2})
boss = M.boss("sanctum", "B8")
disk = M.item("vault", "RedOrb", *free_spot(M, "vault", 6.0, 6.0))
book = M.item("cistern", "BlackBook1", *free_spot(M, "cistern", 4.0, 4.0))
# potions where a player stops between stages: the cistern's dead end, the library (the spiders' poison), the tombs
for rid, t, n in (("cistern", "RedPotion", 1), ("library", "CurePoisonPotion", 1), ("sunroom", "RedPotion", 2),
                  ("tombs", "RedPotion", 1)):
    pa, pb = free_spot(M, rid, 2.0, 2.0, clear=1.2)
    for k in range(n):
        M.put(rid, t, pa + 0.45 * k, pb, clear=2.4)
morgan = M.person("camp", "Con02a", "Morgan", "FatherMorgan", pic="MorganPic", title="Father Morgan")

# ---- the story --------------------------------------------------------------------------------------------------
q = M.q
MAIN, SIDE = "sundisk", "prayerbook"
GOAL = "Bring the sun disk back from the drowned sanctum."
ERRAND = "Find Edwin's prayer book in the cistern."
q.talker(morgan, [
    q.say("May the light keep you always. The temple is in your debt.",
          when=q.at(MAIN, 3)),
    q.say("The sun disk! It shines as it did on the day it was made! You have done the temple a great deed. Please, "
          "accept this gold and my blessing.",
          when=q.at(MAIN, 2, has="RedOrb"),
          do=[A.take("RedOrb"), A.gold(450), A.give("RedPotion", 2), A.stage(MAIN, 3), q.done(GOAL)]),
    q.say("You carry the disk, yet Kesh still lives? He will hunt you for it. Deal with him first.",
          when=q.at(MAIN, 1, has="RedOrb")),
    q.say("Edwin's prayer book! The boy will weep for joy. Take these. The spiders down there carry poison.",
          when=q.when(has="BlackBook1", not_=f"{SIDE}done"),
          do=[A.take("BlackBook1"), A.give("CurePoisonPotion", 2), A.gold(100), A.flag(f"{SIDE}done"),
              q.done(ERRAND)]),
    q.say("Kesh is dead? The light be praised! Now bring me the disk from the vault.",
          when=q.at(MAIN, 2)),
    q.say("Hurry, my son! The disk must not leave the temple.",
          when=q.at(MAIN, 1)),
    q.say("Thank goodness someone has come! The temple's lower halls have been under water since the lake rose.\n\n"
          "A raider called Kesh of the Red Sands broke in with his scorpions. He wants the sun disk, the most holy "
          "thing in the temple! The old priests' traps still guard the way down -- arrows, beams of light, false "
          "floors.\n\n"
          "Will you go down and bring the sun disk back to me? The temple will not forget it.",
          when=q.at(MAIN, 0), ask=True,
          do=[A.stage(MAIN, 1), q.journal(GOAL), q.journal(ERRAND),
              q.tell(morgan, "One more thing. Young Edwin dropped his prayer book in the cistern when the scorpions "
                             "came. Bring it back if you find it.")],
          else_=[q.tell(morgan, "So be it. I shall pray that someone braver comes along.")]),
], pic="MorganPic", title="Father Morgan")
q.on_death(boss, [A.stage(MAIN, 2), q.journal("Take the sun disk from the vault and return to Father Morgan.")])
q.start([q.journal("Speak to Father Morgan at the camp on the temple steps.")])
M.sign("camp", "THE SUNKEN SANCTUM. Pilgrims, beware the lower halls.", *sign_at)

# the healing wells named for the healing script (kit/setpieces HEAL_PREFIX; kit/wells.py heals them all)
for k, o in enumerate(o for o in M.m.d["objects"] if o.get("type") == "WishingWell"):
    o.setdefault("scr", f"HealWell{k + 1}")
m = M.m                                   # tests/server_smoke.py reads the spec as m
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out", "trapdemo", NAME)
M.finish(None if out == "-" else out)
