"""BossLab: ten human bosses, each in its own arena, to fight one by one (dystopiannox mods/BOSSLAB.md; scripts:
kit/behaviours/bosses.go, wired by kit/bosses.py).

The bosses are the game's NPC (a human drawn with the player's own body), dressed in the player's armour, dyed with
the game's colour enchantments, holding the player's weapons, with the game's spells and a scripted way of fighting
each. Two of them (B3 the Golemwright, B4 Mortivane) raise major minions.

- the hall: a long gallery, the start at its west end with a chest of potions and a sign;
- ten arenas off the hall, five to the north-east (B1-B5) and five to the south-west (B6-B10), each through a gap in
  the hall's wall with the boss's sign beside it; the boss waits frozen until you walk in (or strike it), and comes
  back 30 seconds after it dies, twice;
- pillars stand in the arenas where they change the fight (the warlord's charge, the ranger's range, the assassin's
  stalking);
- a sealed vault west of the hall holds the bosses' spare copies.

    py mapgen/designs/bosslab.py [out_dir|-]
"""
import json, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from nox import Spec, SOLO, px, uv_to_xy
from kit.bosses import Bosses, BOSSES

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "BossLab"
m = Spec(NAME, summary="Boss lab", description="[env:castle] Ten human bosses in the player's own armour and weapons, "
         "each with its own way of fighting. Generated by Claude.", author="vdystopia (generated by Claude)",
         version="0.1", date="2026", type=SOLO, minPlayers=1, maxPlayers=1)
m.d["nxz"] = False
m.d["ambient"] = [205, 200, 195]
m.loot = False
P = lambda u, v: px(u, v)
TEXT = {}


def text(key, s):
    k = f"{NAME}:{key}"
    assert len(k) <= 31, k
    TEXT[k] = s
    return k


def sign(key, s, u, v, step=(0, -3)):
    """A small sign, or a short row of them (a sign prints one line; a long text crashes the client: kit/signs.py)."""
    from kit.signs import wrap, SIGN_WARN
    for k, part in enumerate(wrap(s)):
        assert len(part) <= SIGN_WARN, (key, part)
        m.obj_px("Sign1", *P(u + step[0] * k, v + step[1] * k), xfer={"Text": text(key if not k else f"{key}_{k + 1}", part)})


def gate(u_mid, v):
    """A three-cell opening in the wall line at v (rect walls run along u in steps of 2)."""
    for u in (u_mid - 2, u_mid, u_mid + 2):
        m.remove_wall(*(int(c) for c in uv_to_xy(u, v)))


def pillar(u, v, wall="StoneGray"):
    """A free-standing block of wall (one cell): cover, and something to charge into."""
    x, y = (int(c) for c in uv_to_xy(u, v))
    m.wall(x, y, wall, facing=2)                # a cross piece: a post standing free


# ---- the rooms --------------------------------------------------------------------------------------------------
W = 44                                        # an arena is W x W uv units (about 720 px a side)
U0 = 204                                      # the first arena's west edge
HALL = (196, U0 + 5 * W + 8, -16, 16)
m.room(*HALL, wall="BrickPlain", floor="CobbleStone")
# B1-B5 north-east of the hall, B6-B10 south-west: (id, floor)
NE = [("B1", "TileDark"), ("B2", "DirtHard"), ("B3", "GrassNorm"), ("B4", "LOTDPitted"), ("B5", "DirtDark2")]
SW = [("B6", "DirtLight2"), ("B7", "CobbleStone"), ("B8", "VolcanicCraggy"), ("B9", "VolcanicCraggy"),
      ("B10", "LOTDBlackMarble")]
# pillars by boss, in arena-local uv (0..W): cover where it changes the fight
# (none on the line from the gate to the boss: the ranger must see you come in)
PILLARS = {"B2": [(12, 14), (32, 14), (12, 30), (32, 30)],
           "B5": [(12, 18), (32, 18), (10, 34), (34, 34)],
           "B6": [(10, 14), (34, 14), (14, 36), (30, 36)]}

bosses = Bosses(m)
VAULT = (146, 186, -24, 24)                  # sealed, west of the hall (the grid ends at 256 cells): the spares wait here
m.room(*VAULT, wall="BrickPlain", floor="CobbleStone")
spare_slots = [P(VAULT[0] + 5 + 4 * (k % 8), VAULT[2] + 6 + 6 * (k // 8)) for k in range(40)]


def arena(k, bid, floor, side):
    u0 = U0 + W * k
    if side > 0:
        v0, v1, door_v = 16, 16 + W, 16
    else:
        v0, v1, door_v = -16 - W, -16, -16
    m.room(u0, u0 + W, v0, v1, wall="BrickPlain", floor=floor)
    mid = u0 + W // 2
    gate(mid, door_v)
    for pu, pv in PILLARS.get(bid, []):
        pillar(u0 + pu, v0 + pv if side > 0 else v1 - pv)
    # the boss stands two thirds of the way in, facing the gate; its sign beside the gate in the hall
    far = v0 + W * 0.66 if side > 0 else v1 - W * 0.66
    gate_pt = P(mid, door_v)
    spares = [spare_slots.pop(0), spare_slots.pop(0)]
    bosses.boss(bid, *P(mid, far), face=gate_pt, spares=spares, engage=320.0, respawn=30.0)
    sign(bid, BOSSES[bid]["text"], mid + 4, door_v - 3 * side, step=(4, 0))


for k, (bid, fl) in enumerate(NE):
    arena(k, bid, fl, +1)
for k, (bid, fl) in enumerate(SW):
    arena(k, bid, fl, -1)

# ---- the start --------------------------------------------------------------------------------------------------
sign("Welcome", "BOSSLAB: ten human bosses in your own kind of armour. Each waits in its arena until you walk in, and "
     "comes back 30 seconds after it dies, twice. Read the sign by each gate.", 202, -6)
m.obj_px("Chest4", *P(200, 10), items=["RedPotion"] * 8 + ["BluePotion"] * 4 + ["CurePoisonPotion"] * 3)
m.obj_px("PlayerStart", *P(202, 0))
bosses.attach()

out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out")
if out_dir != "-":
    os.makedirs(out_dir, exist_ok=True)       # the text first: the build's checker reads the signs' text beside the map
    with open(os.path.join(out_dir, f"{NAME}.strings.json"), "w", encoding="utf-8") as f:
        json.dump(TEXT, f, ensure_ascii=False, indent=1)
    lines = m.build(out_dir)
    print("\n".join(l for l in lines if l.startswith(("OK", "ERROR", "CHECK", "SCRIPTS"))))
print(f"bosses {len(bosses.calls)} | NPCs {len(bosses.placed)} | signs {len(TEXT)}")
