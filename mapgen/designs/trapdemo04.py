"""TrapDemo 04: The Collapsed Seam (map TrapDem04; kit/trapdemo.py Mission). A mine whose deep seam a golemwright
has taken.

The story
- The hook: Foreman Brannoc has camped at the pithead with his crew. They struck a great ruby, the heartstone, in the
  deep seam; then the seam fell in, and the conjurer Oskar Thorne, the Golemwright, came down after the stone and
  raised golems out of the rock to hold it. The old workings are rotten floors, shafts and blasting gear.
- Main quest (the heartstone): get down to the deep seam, put down Oskar Thorne (his hold on the seam breaks with
  him) and bring the heartstone (a Ruby) back from the binding chamber beyond. Brannoc pays in gold.
- Side quest (Wynn): the old miner Wynn went down for the last cart and never came up. His torch lies in the old
  drift off the winch house, beyond a rotten floor; he did not make it. Brannoc gives Wynn's last pay for it.
- The traps, in the order a player meets them: plates that open the floor ahead in the first gallery; the ore
  belts, each running into a chasm; the breathing vice into the winch house; stepping stones over a rotten floor to
  the old drift (the side quest); the block gauntlet (jaws, rams, a swept bridge over the drop, a vice) into the
  golemwright's workshop; the tilting floor between two pit fields to the deep seam. The cistern off the tool store,
  with its well, is the rest.

    py mapgen/designs/trapdemo04.py [out_dir|-]
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from kit.trapdemo import Mission
from kit.quests import A
from kit.trapdemo_dress import kit_camp, open_spot, wall_spot, chest, extra, thin
from kit.setpieces import healing_well, ensure_blends, PAD
from kit.layout import square_px, square_tile

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "TrapDem04"
M = Mission(NAME, "The Collapsed Seam", "mine", seed=4, ambient=(95, 90, 85),
            description="[env:cave] TrapDemo 04, The Collapsed Seam: a mine of rotten floors, shafts and grinding "
                        "blocks, its deep seam held by the golemwright Oskar Thorne. Generated by Claude.")
M.room("pithead", (14, 12), role="camp", start=True)
M.room("tools", (14, 12), role="store", kind="gear_store")
M.room("cistern", (12, 12), role="room", kind="cellar")
M.room("bunks", (14, 12), role="guard", kind="barracks")
M.room("winch", (16, 14), role="room", kind="winch_room")
M.room("drift", (12, 12), role="store", kind="ore_store")
M.room("works", (14, 12), role="room", kind="laboratory")
M.room("seam", (18, 16), role="boss")                   # a cave hall: open ground for the fight
M.room("heart", (12, 12), role="vault", kind="coven")
M.link("pithead", "tools", trap=("pit", 2))                  # look before you leap: plates that open the floor ahead
M.link("tools", "cistern", length=6)                         # the rest: the miners' well
M.link("tools", "bunks", trap=("push", 1))                   # the ore belts, each running into a chasm
M.link("bunks", "winch", trap=("block", 4))                  # the breathing vice
M.link("winch", "drift", trap=("pit", 5))                    # stepping stones on a rotten floor: Wynn's last walk
M.link("winch", "works", trap=("block", 9))                  # the block gauntlet: jaws, rams, a swept bridge, a vice
M.link("works", "seam", trap=("push", 8))                    # the tilting floor between two pit fields
M.link("seam", "heart", length=5)
M.layout()
pithead = M.rooms.pop("pithead")                             # the pithead is laid by the camp kit, the rest by the room kit
M.dress()
M.rooms = {"pithead": pithead, **M.rooms}
camp = kit_camp(M, "pithead", trade="dig", sleepers=4, tents=1, loot=[("Gold", {"Amount": 30}), "RedPotion", "RedPotion"])
M.start_at("pithead")
# the tool store: the miners' gear on its racks (the room kit), their carts and tool barrels laid by
tw_, th_ = M.rooms["tools"]["size"]
extra(M, "tools", [("MineOreCart1", 4.2, th_ - 3.2), ("BarrelWithTools1", tw_ - 1.0, 2.2), ("BarrelWithTools2", tw_ - 1.0, 3.3),
                   ("Crate1", tw_ - 3.0, 1.0), ("CrateSteel1", 4.0, th_ - 0.9), ("BarrelSteel1", 5.2, th_ - 0.9),
                   ("WaterBarrel", 0.9, 9.0), ("MineOreCartWheel", tw_ - 4.0, th_ - 3.0), ("Crate2", tw_ - 1.1, th_ - 3.0),
                   ("BarrelSteel2", 1.0, th_ - 1.0), ("MineOreCart1", tw_ - 4.5, 3.0)], clear=1.1, reach=3.0)
# the pithead: the camp kit's camp by the hearth, the mine's own gear by the far walls
pw_, ph_ = M.rooms["pithead"]["size"]
extra(M, "pithead", [("MineOreCart1", 3.6, 2.4), ("CrateSteel1", 1.1, 3.6), ("BarrelWithTools2", 1.0, 4.8),
                     ("CaveRocksLarge", 5.0, 0.9), ("WaterBarrel", 0.9, ph_ - 2.6), ("Crate2", 0.9, ph_ - 1.4)],
      clear=1.1, reach=2.0)
thin(M, "winch", r"^(Barrel|BarrelSteel|BarrelWithTools|WaterBarrel|Crate|CrateSteel|DarkCrate)", keep=0.5)
# the deep seam: the cave's pillars (Mission.dress), crystal growing out of the back walls, the last ore carts
sw_, sh_ = M.rooms["seam"]["size"]
extra(M, "seam", [("MineCrystalUp01", 3.0, sh_ - 1.0), ("MineCrystalUp03", 6.5, sh_ - 0.9), ("MineCrystalUp05", 11.5, sh_ - 1.0),
                  ("MineCrystalUp02", 15.0, sh_ - 0.9), ("MineCrystalUp04", 1.0, 4.0), ("MineCrystalUp01", 0.9, 11.5),
                  ("MineOreCart1", 2.2, 7.6), ("MineManaCart1", sw_ - 2.4, 3.2), ("CaveRocksLarge", sw_ - 1.4, 9.0),
                  ("CaveBoulders", 4.5, 1.3)], clear=1.2, reach=1.5)

# ---- the plot's things, the rest, loot --------------------------------------------------------------------------
hw, hh = M.rooms["heart"]["size"]
stone = M.item("heart", "Ruby", *open_spot(M, "heart", hw / 2, hh / 2))
ta, tb = open_spot(M, "drift", 6, 6, clear=1.1)
torch = M.item("drift", "TorchInventory", ta, tb)
for t, da_, db_ in (("Skull", 0.6, 0.5), ("ArmBone", -0.5, 0.6), ("LegBone", 0.4, -0.6)):  # Wynn, who did not make it
    M.m.obj_px(t, *M.at("drift", ta + da_, tb + db_))
cw, ch = M.rooms["cistern"]["size"]
wa, wb = open_spot(M, "cistern", cw / 2, ch / 2, clear=2.0)  # the miners' well: the healing well (kit/setpieces.py)
healing_well(M.m, *M.at("cistern", wa, wb))
for (i, j) in M.parts["cistern"].squares:                    # on its own paving
    a_, b_ = M.room_ab("cistern", *square_px(i + 0.5, j - 0.5))
    if abs(a_ - wa) < 2.0 and abs(b_ - wb) < 2.0: M.m.floor[square_tile(i, j)] = PAD
ensure_blends(M.m)
for s_ in (-1, 1):
    M.m.obj_px("WaterBarrel", *M.at("cistern", wa + 1.45 * s_, wb + 0.2))
M.m.obj_px("Sign1", *M.at("cistern", wa - 1.4, wb + 1.6))      # a sign with no text by a well reads "Magical Well"
for k, t in enumerate(("RedPotion", "RedPotion")):
    M.m.obj_px(t, *M.at("cistern", wa + 0.6 + 0.45 * k, wb - 1.5))
ww, wh = M.rooms["works"]["size"]
spot = wall_spot(M, "works", ("NE", "NW", "SE"), clear=1.45) or open_spot(M, "works", ww / 2, wh / 2, clear=1.2)
chest(M, "works", *spot, [("Gold", {"Amount": 140}), "RedPotion", "BluePotion", "ShockProtectPotion"])

# ---- life -------------------------------------------------------------------------------------------------------
M.monsters("tools", {"Bat": 3})
M.monsters("bunks", {"SmallSpider": 3, "Spider": 1})
M.monsters("winch", {"GiantLeech": 2, "Troll": 1})
M.monsters("drift", {"Bat": 2})
M.monsters("works", {"StoneGolem": 1, "Wolf": 2})
M.monsters("seam", {"Wolf": 2})
boss = M.boss("seam", "B3")
brannoc = M.person("pithead", "Con03A", "Rastur", "ForemanBrannoc", *M.room_ab("pithead", *camp["leader"]),
                   face=camp["fire"], pic="MalePic9", title="Foreman Brannoc")

# ---- the story --------------------------------------------------------------------------------------------------
q = M.q
MAIN, SIDE = "heartstone", "wynn"
HOLD = "Break Oskar Thorne's hold on the deep seam."
BRING = "Bring the heartstone from the deep seam to Brannoc."
WYNN = "Find what became of Wynn in the old drift."
q.talker(brannoc, [
    q.say("The heartstone! By all that's holy, you did it! Here's your pay -- 500 in gold. The lads will drink to "
          "you tonight.",
          when=q.when(has="Ruby", not_=f"{MAIN}done"),
          do=[A.take("Ruby"), A.gold(500), A.stage(MAIN, 3), A.flag(f"{MAIN}done"), q.done(BRING)]),
    q.say("That's Wynn's torch. He went down for the last cart when the floor gave way. Poor old Wynn... Here, take "
          "his pay. He'd want it spent, not buried.",
          when=q.when(has="TorchInventory", not_=f"{SIDE}done"),
          do=[A.take("TorchInventory"), A.gold(150), A.flag(f"{SIDE}done"), q.done(WYNN)],
          mood="gruff, grieving"),
    q.say("The seam's ours again, thanks to you.", when=q.at(MAIN, 3)),
    q.say("Thorne's dead? Ha! Then bring up the heartstone before the roof comes down on it.", when=q.at(MAIN, 2)),
    q.say("The lads are counting on you. Go on, before the whole seam comes down!", when=q.at(MAIN, 1)),
    q.say("The deep seam's caved in, and that's not the worst of it! We struck a ruby down there the size of your "
          "fist -- the heartstone, the lads call it. Then a conjurer named Oskar Thorne came down after it. He "
          "raised golems out of the rock to keep us out.\n\nMy crew won't go back below. The old workings are all "
          "rotten floors and shafts now.\n\nGo down to the deep seam, break Thorne's hold on it, and bring me the "
          "heartstone. Will you do it, stranger? The company pays well.",
          ask=True,
          do=[A.stage(MAIN, 1), q.journal(HOLD), q.journal(WYNN)],
          else_=[q.tell(brannoc, "Then the mine's finished, and so are we.")]),
], pic="MalePic9", title="Foreman Brannoc")
q.on_death(boss, [A.stage(MAIN, 2), q.done(HOLD), q.journal(BRING),
                  q.note("Oskar Thorne is dead. His hold on the deep seam is broken.")])
q.start([q.journal("Speak to Foreman Brannoc at the pithead.")])
M.sign("pithead", "GREYFELL MINE. Deep seam closed.", 2.0, 1.2)

m = M.m                                   # tests/server_smoke.py reads the spec as m
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out", "trapdemo", NAME)
M.finish(None if out == "-" else out)
