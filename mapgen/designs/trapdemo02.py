"""TrapDemo 02: The Cinder Foundry (map TrapDem02; kit/trapdemo.py Mission). A guild foundry gone wild under a
pyromancer.

The story
- The hook: Foundry-master Hask has camped in the loading yard with what is left of his guild. The pyromancer Ignis
  Varr took the crucible hall and fed the furnaces until they ran wild; the guild fled and Imps and fire demons came
  up through the flues. The guild built its own works to be dangerous to strangers: flame grates, presses, pushers.
- Main quest (the Master's Hammer): pull the quench lever in the furnace hall (it drowns the furnace and opens the
  crucible door), put down Ignis Varr in the crucible hall and bring the Master's Hammer back from the guild vault.
  Hask pays in gold.
- Side quest (the guild ledger): the ledger was left in the cold store, off the casting floor behind a pair of
  presses. Hask gives fire-ward potions for it (useful against Varr).
- The traps, in the order a player meets them: flame grates on a clock at the way in; the snapping presses before the
  cold store (taught in a side room); the pushers on the beat into the guild hall; two lanes of fire to the bunkhouse;
  the block gauntlet to the furnace hall (the presses again, and a ram wave, a swept bridge and a vice); belt and
  pistons before the armoury (a side room of loot). The powder store off the guild hall is the rest before the hard
  half.

    py mapgen/designs/trapdemo02.py [out_dir|-]
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from kit.trapdemo import Mission
from kit.trapkit import Station
from kit.quests import A
from kit.trapdemo_dress import kit_camp, open_spot, wall_spot, clear_around, chest

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "TrapDem02"
M = Mission(NAME, "The Cinder Foundry", "forge", seed=2, ambient=(120, 100, 90),
            description="[env:castle] TrapDemo 02, The Cinder Foundry: a guild foundry whose furnaces run wild under "
                        "the pyromancer Ignis Varr; the guild's own flame grates, presses and pushers guard it. "
                        "Generated by Claude.")
M.room("yard", (14, 12), role="camp", start=True)
M.room("casting", (16, 14), role="guard", kind="workshop")
M.room("coldstore", (12, 12), role="store", kind="storeroom")
M.room("guildhall", (18, 14), role="room", kind="great_hall")
M.room("powder", (12, 12), role="store", kind="powder_store")
M.room("bunks", (14, 12), role="guard", kind="barracks")
M.room("furnace", (14, 12), role="room", kind="smithy")
M.room("armoury", (14, 12), role="store", kind="gear_store")
M.room("crucible", (18, 16), role="boss", kind="hall")
M.room("vault", (12, 12), role="vault", kind="treasury")
M.link("yard", "casting", trap=("flame", 0))                 # grates on a clock: the way in
M.link("casting", "coldstore", trap=("block", 1))            # the snapping presses: the side quest's price
M.link("casting", "guildhall", trap=("push", 0))             # pushers on the beat
M.link("guildhall", "powder", length=5)                      # the rest before the hard half
M.link("guildhall", "bunks", trap=("flame", 5))              # two lanes of fire
M.link("bunks", "furnace", trap=("block", 9))                # the block gauntlet: the presses again, and worse
M.link("furnace", "armoury", trap=("push", 6))               # belt and pistons: the armoury's loot
M.link("furnace", "crucible", length=6)                      # the crucible door: the quench lever opens it
M.link("crucible", "vault", length=5)
M.layout()
yard = M.rooms.pop("yard")                                   # the yard is laid by the camp kit, the rest by the room kit
M.dress()
M.rooms = {"yard": yard, **M.rooms}
camp = kit_camp(M, "yard", trade="bandit", sleepers=4, tents=2, loot=[("Gold", {"Amount": 30}), "RedPotion", "RedPotion"])
M.start_at("yard")


# ---- the quench lever, the furnace and the crucible door -----------------------------------------------------------
def link_part(a, b):
    return next(L_["part"] for L_ in M.links if L_["a"] == a and L_["b"] == b)


door = Station(M.T, link_part("furnace", "crucible"), "QD", M.rng, spec=M.m)
gate = door.gate(1.0, state="closed")                       # a wall across the corridor a square in from the hall
fw, fh = M.rooms["furnace"]["size"]
da, db = M.room_ab("furnace", *link_part("furnace", "crucible").at(0, 2))
# the lever stands by the wall the door is in, three squares to one side of it, the room kit's pieces lifted off it
if min(da, fw - da) < min(db, fh - db):                    # the door is in a NW (a=0) or SE (a=w) wall
    la, lb = (0.7 if da < fw / 2 else fw - 0.7), db + 3.2
else:                                                      # in a SW (b=0) or NE (b=h) wall
    la, lb = da + 3.2, (0.7 if db < fh / 2 else fh - 0.7)
clear_around(M, "furnace", la, lb, 1.3)
lever_xy = M.at("furnace", la, lb)
# the runaway furnace: fire roaring on the forge's hearth, which the lever drowns
forge = [o for o in M.m.d["objects"] if o.get("type", "").startswith(("CinderBin", "Forge"))
         and 0 < M.room_ab("furnace", o["x"], o["y"])[0] < fw and 0 < M.room_ab("furnace", o["x"], o["y"])[1] < fh]
fire = []
if forge:
    ga, gb = M.room_ab("furnace", forge[0]["x"], forge[0]["y"])
    ia, ib = (fw / 2 - ga), (fh / 2 - gb)
    n = (ia * ia + ib * ib) ** 0.5 or 1.0
    ia, ib = ia / n, ib / n                                 # from the forge toward the middle of the hall
    for s_ in (-0.7, 0.0, 0.7):
        fire.append(M.T.obj("LargeFlame", *M.at("furnace", ga + ia * 1.1 - ib * s_, gb + ib * 1.1 + ia * s_),
                            name=f"FurnaceFire{len(fire) + 1}"))
    M.T.group("FurnaceFire", fire)
M.T.lever("QuenchLever", "FloorLever1", *lever_xy, once=True,
          acts=[M.T.act("walls_open", walls=gate), M.T.act("off", "FurnaceFire"),
                M.T.act("sound", text="BigGong", src=lever_xy)])

# ---- the plot's things, loot ------------------------------------------------------------------------------------
vw, vh = M.rooms["vault"]["size"]
hammer = M.item("vault", "WarHammer", *open_spot(M, "vault", vw / 2, vh / 2))
ledger = M.item("coldstore", "BlackBook1", *open_spot(M, "coldstore", 6, 6))
pa, pb = open_spot(M, "powder", 6, 6, clear=1.2)
for k, t in enumerate(("RedPotion", "RedPotion", "RedPotion", "BluePotion")):
    M.m.obj_px(t, *M.at("powder", pa + 0.45 * (k % 2), pb + 0.45 * (k // 2)))
aw, ah = M.rooms["armoury"]["size"]
ca, cb = wall_spot(M, "armoury", ("NE", "NW", "SE"), clear=1.45) or open_spot(M, "armoury", aw / 2, ah / 2 + 2, clear=1.2)
chest(M, "armoury", ca, cb, [("Gold", {"Amount": 150}), "FireProtectPotion", "RedPotion", "RedPotion", "BluePotion"])
for k, t in enumerate(("Longsword", "SteelShield")):
    M.item("armoury", t, *open_spot(M, "armoury", aw / 2 + 1.5 * (k * 2 - 1), ah / 2, clear=1.0))

# ---- life -------------------------------------------------------------------------------------------------------
M.monsters("casting", {"Imp": 3})
M.monsters("coldstore", {"FireSprite": 1})
M.monsters("guildhall", {"Imp": 2, "FireSprite": 2})
M.monsters("bunks", {"FireSprite": 2, "EmberDemon": 1})
M.monsters("furnace", {"EmberDemon": 2, "FireSprite": 1})
M.monsters("armoury", {"MeleeDemon": 1, "EmberDemon": 1})
boss = M.boss("crucible", "B9")
hask = M.person("yard", "Con02a", "Bryan", "Hask", *M.room_ab("yard", *camp["leader"]), face=camp["fire"],
                pic="QuarterMasterPic", title="Foundry-master Hask")

# ---- the story --------------------------------------------------------------------------------------------------
q = M.q
MAIN, SIDE = "hammer", "ledger"
LEVER = "Pull the quench lever in the furnace hall."
VARR = "Defeat Ignis Varr in the crucible hall."
BRING = "Bring the Master's Hammer from the guild vault to Hask."
LEDGER = "Find the guild ledger in the cold store."
q.talker(hask, [
    q.say("The Master's Hammer! You did it! The guild is saved, and the forges will ring again. Here is your "
          "reward -- 500 in gold, and well earned.",
          when=q.at(MAIN, 3, has="WarHammer"),
          do=[A.take("WarHammer"), A.gold(500), A.stage(MAIN, 4), q.done(BRING)]),
    q.say("Our ledger! Without it we would never know who owes the guild what. Take these potions. They keep the fire "
          "off your skin.",
          when=q.when(has="BlackBook1", not_=f"{SIDE}done"),
          do=[A.take("BlackBook1"), A.give("FireProtectPotion", 2), A.flag(f"{SIDE}done"), q.done(LEDGER)]),
    q.say("The guild won't forget you, Adventurer!", when=q.at(MAIN, 4)),
    q.say("Varr is dead? Then the vault is open. Bring me the Master's Hammer.", when=q.at(MAIN, 3)),
    q.say("I heard the furnace die from here. Now for Varr, before he lights it again.", when=q.at(MAIN, 2)),
    q.say("What are you waiting for? Every hour that furnace burns, the foundry melts a little more!",
          when=q.at(MAIN, 1)),
    q.say("It's a disaster! A pyromancer called Ignis Varr took the crucible hall and stoked the furnaces until they "
          "ran wild. Fire demons came up the flues and my people ran for their lives.\n\nThe quench lever in the "
          "furnace hall will drown the furnace and open the crucible door. It lies deep in, past the bunkhouse. Pull "
          "it, deal with Varr, and bring back the Master's Hammer from the guild vault. Will you help us, kind "
          "stranger? The guild pays its debts.",
          ask=True,
          do=[A.stage(MAIN, 1), q.journal(LEVER), q.journal(LEDGER)],
          else_=[q.tell(hask, "Then the Cinder Foundry burns, and the guild with it.")]),
], pic="QuarterMasterPic", title="Foundry-master Hask")
q.near(*lever_xy, 44.0, [A.stage(MAIN, 2), q.done(LEVER), q.journal(VARR)], when=q.at(MAIN, 1))
q.on_death(boss, [A.stage(MAIN, 3), q.done(VARR), q.journal(BRING),
                  q.note("Ignis Varr is dead. The guild vault lies open beyond the crucible hall.")])
q.start([q.journal("Speak to Foundry-master Hask in the loading yard.")])
M.sign("yard", "THE CINDER FOUNDRY. Guild hands only.", 2.0, 1.2)

m = M.m                                   # tests/server_smoke.py reads the spec as m
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out", "trapdemo", NAME)
M.finish(None if out == "-" else out)
