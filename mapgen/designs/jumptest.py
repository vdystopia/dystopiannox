"""JumpTest: how deep a hazard a real jump clears (tests/traps_e2e/jumptest.py: the e2e input runs down the hall and
presses jump before each strip; a probe logs the hero's health and place every frame).

A straight hall along i, 4 squares wide, five strips of standing spikes wall to wall, 1.5, 2.0, 2.5, 3.0 and 3.5
squares deep, starting at a = 6, 14, 22, 30, 38 (8 squares apart: the stamina comes back between jumps).

    py mapgen/designs/jumptest.py [out_dir|-]
"""
import json, os, random, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from nox import Spec, SOLO
from kit.dungeon import Dungeon
from kit.traps import Traps
from kit.trapkit import Station

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "JumpTest"
STRIPS = [(6.0, 1.5), (14.0, 2.0), (22.0, 2.5), (30.0, 3.0), (38.0, 3.5)]
m = Spec(NAME, summary="Jump test", description="[env:castle] Strips of spikes 1.5 to 3.5 squares deep, to measure "
         "what a jump clears. Generated by Claude.", author="vdystopia (generated by Claude)", version="0.1",
         date="2026", type=SOLO, minPlayers=1, maxPlayers=1)
m.d["nxz"] = False
m.d["ambient"] = [200, 200, 200]
m.loot = False
d = Dungeon(m, random.Random(1), wall="DungeonStone", floor="GreenBrick")
hall = d.box("hall", 100, 0, 48, 4)
d.apply()
T = Traps(m, prefix="J")
st = Station(T, hall, "J", random.Random(1))
for k, (a, dep) in enumerate(STRIPS):
    st.carpet(f"S{k}", a, a + dep, 0.05, 3.95, enabled=True)
start = hall.at(1.0, 2.0)
m.obj_px("PlayerStart", *hall.at(0.6, 2.0))
T.attach()
INFO = dict(start=list(start), strips=STRIPS, origin=list(hall.at(0, 0)), along=list(hall.direction()),
            across=list(hall.across()))
out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out")
if out_dir != "-":
    os.makedirs(out_dir, exist_ok=True)
    lines = m.build(out_dir)
    json.dump(INFO, open(os.path.join(out_dir, f"{NAME}.jump.json"), "w"), indent=1)
    print("\n".join(l for l in lines if l.startswith(("OK", "ERROR", "CHECK", "SCRIPTS"))))
