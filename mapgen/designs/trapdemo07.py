"""TrapDemo 07: The Quiet Catacombs (map TrapDem07; kit/trapdemo.py Mission). Old catacombs under a town, where an
assassin hides among the dead.

The story
- The hook: Widow Maren waits at the gate of the old catacombs. Three nights ago the assassin Silas Vane, the Quiet
  Knife, killed her husband Tomas, a jeweller, and took the diamond he was cutting. Vane hides below, where the town's
  dead lie and the old priests' traps still work; the guards will not go down.
- Main quest (the diamond): go down past the traps and the dead, put down Silas Vane in his lair and bring Tomas's
  diamond up from his hoard beyond it. Maren pays in gold on the way back.
- Side quest (the book of the dead): the old chapel off the upper crypt keeps the priests' black book with the names
  of the dead; Maren wants it to write Tomas's name in. The chapel lies beyond a floor of pits to read before
  leaping. She gives potions.
- The traps, in the order a player meets them: two spike fields in turn at the way down (cheap to get wrong); the
  chapel's pits; gas vents before the old cells (the stores); the jaws to the torture chamber; then the hard
  half: the checkerboard of spikes, the stepping stones over the drop, and the ledge of stabbing blades over a pit
  before Vane's lair.

    py mapgen/designs/trapdemo07.py [out_dir|-]
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from kit.trapdemo import Mission
from kit.trapdemo_dress import camp, clear_mouths, start_spot, free_spot, extra, thin
from kit.quests import A

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "TrapDem07"
M = Mission(NAME, "The Quiet Catacombs", "crypt", seed=7, ambient=(100, 100, 95),
            description="[env:castle] TrapDemo 07, The Quiet Catacombs: old catacombs under a town, where an "
                        "assassin hides among the dead behind the priests' spikes, pits and blades. Generated by "
                        "Claude.")
M.room("camp", (14, 12), role="camp", start=True, closed=("NE", "NW"))
M.room("crypt", (14, 12), role="crypt", kind="crypt")
M.room("chapel", (14, 12), role="shrine", kind="chapel")
M.room("ossuary", (16, 14), role="crypt", kind="ossuary")
M.room("cells", (14, 12), role="store", kind="cell")
M.room("torture", (16, 14), role="guard", kind="torture_chamber")
M.room("mausoleum", (16, 14), role="crypt", kind="mausoleum")
M.room("deep", (16, 12), role="crypt", kind="dark_crypt", style="lotd")
M.room("lair", (18, 14), role="boss", kind="hall")
M.room("hoard", (12, 12), role="vault", kind="treasury")
M.link("camp", "crypt", trap=("spike", 1))                    # two fields in turn: the way down
M.link("crypt", "chapel", trap=("pit", 2))                    # look before you leap: the side quest's price
M.link("crypt", "ossuary", length=6)
M.link("ossuary", "cells", trap=("spell", 1))                 # gas vents before the old cells
M.link("ossuary", "torture", trap=("blade", 1))               # the jaws
M.link("torture", "mausoleum", trap=("spike", 6))             # the checkerboard (hard)
M.link("mausoleum", "deep", trap=("pit", 5))                  # stepping stones (hard)
M.link("deep", "lair", trap=("blade", 7))                     # the ledge over the pit (hard)
M.link("lair", "hoard", length=5)
M.layout()
n0 = len(M.m.d["objects"])
M.dress()
cleared = clear_mouths(M, M.m.d["objects"][n0:])
camp(M, "camp")
M.start_at("camp", *start_spot(M, "camp"))
# the torture chamber's bones: under half of them (strewn over its whole floor they read as clutter), and more of
# its work: iron maidens on the NE wall, a second rack, stocks by the SW wall, a brazier for the irons
thin(M, "torture", r"^(Skull|ArmBone|LegBone)$", keep=0.4)
w, h = M.rooms["torture"]["size"]
extra(M, "torture", [("IronMaiden1", 2.2, h - 1.0), ("IronMaiden1", 1.0, h - 2.4), ("IronMaiden1", w - 1.0, h - 2.6),
                     ("TortureRack6", w / 2 + 3.2, h / 2 - 1.5), ("Stocks1", w - 4.0, 1.2), ("Stocks1", w - 6.0, 1.2),
                     ("SpikeBrazier", w / 2 - 3.0, h / 2 + 1.5)], clear=1.4, reach=1.5)
# the ossuary, a crossroads: coffins along its back walls between the ways, bone heaps in its corners
w, h = M.rooms["ossuary"]["size"]
extra(M, "ossuary", [("Coffin1", 3.0, h - 1.1), ("Coffin3", w - 3.0, h - 1.1), ("Coffin2", 1.1, 3.0),
                     ("Coffin4", 1.1, h - 3.4), ("SkullImmobile", w - 1.4, 1.4), ("ArmBoneImmobile", w - 2.1, 1.1),
                     ("LegBoneImmobile", w - 1.2, 2.2), ("SkullImmobile", 1.6, 1.4), ("Candleabra3", w - 1.3, h - 1.3)],
      clear=1.3, reach=1.5)
# the old cells: straw and a bucket in the W corner, bones in the N corner, a stool for the gaoler
w, h = M.rooms["cells"]["size"]
extra(M, "cells", [("CryptChest4", w / 2, h - 1.3, {"items": ["CurePoisonPotion", "BluePotion", ("Gold", {"Amount": 120})]}),
                   ("Straw1", 1.6, 1.8), ("Straw2", 2.6, 1.3), ("WaterBarrel", 3.6, 1.1), ("SkullImmobile", 1.5, h - 1.5),
                   ("ArmBoneImmobile", 2.4, h - 1.2), ("Stool1", w / 2 - 2.5, h - 2.6), ("Stocks4", w / 2 + 1.8, 1.3)],
      clear=1.2, reach=1.5)

# ---- life -------------------------------------------------------------------------------------------------------
M.monsters("crypt", {"Bat": 2, "Skeleton": 2})
M.monsters("chapel", {"Ghost": 2})
M.monsters("ossuary", {"Skeleton": 2, "Zombie": 2})
M.monsters("cells", {"Zombie": 2})
M.monsters("torture", {"Skeleton": 2, "SkeletonLord": 1, "Zombie": 1})
M.monsters("mausoleum", {"SkeletonLord": 1, "Ghost": 2, "Zombie": 1})
M.monsters("deep", {"SkeletonLord": 2, "Shade": 2})
boss = M.boss("lair", "B5")

DIAMOND, BOOK = "Diamond", "BlackBook2"
w, h = M.rooms["hoard"]["size"]
M.item("hoard", DIAMOND, *free_spot(M, "hoard", w / 2, h / 2 - 1.0))
w, h = M.rooms["chapel"]["size"]
M.item("chapel", BOOK, *free_spot(M, "chapel", w / 2, h - 3.0))
# potions where a player stops between stages: the ossuary after the way down, the old cells' stores, the mausoleum
# after the checkerboard, the deep crypt before the ledge
for rid, n in (("ossuary", 2), ("cells", 3), ("mausoleum", 2), ("deep", 1)):
    w, h = M.rooms[rid]["size"]
    pa, pb = free_spot(M, rid, 2.0, 2.0, clear=1.2)
    for k in range(n):
        M.put(rid, "RedPotion", pa + 0.45 * k, pb, clear=2.4)
maren = M.person("camp", "Con02a", "Gretchen", "WidowMaren", pic="MaidenPic4", title="Widow Maren")

# ---- the story --------------------------------------------------------------------------------------------------
q = M.q
MAIN, SIDE = "diamond", "deadbook"
J_MAIN = "Bring back Tomas's diamond from the lair of Silas Vane."
J_SIDE = "Bring the book of the dead from the old chapel."
q.talker(maren, [
    q.say("Thanks again, kind stranger. Tomas can rest now.", when=q.at(MAIN, 3)),
    q.say("Tomas's diamond! And Silas Vane is dead? Oh, thank you! Here's your reward -- 500 in gold!",
          when=q.at(MAIN, 2, has=DIAMOND),
          do=[A.take(DIAMOND), A.gold(500), A.stage(MAIN, 3), q.done(J_MAIN)]),
    q.say("The book of the dead! Now Tomas will be remembered with the others. Take these potions. He never used "
          "them.",
          when=q.at(SIDE, 1, has=BOOK),
          do=[A.take(BOOK), A.give("HastePotion", 2), A.stage(SIDE, 3), q.done(J_SIDE)]),
    q.say("Oh, please, help me!\n\n"
          "Three nights ago a man called Silas Vane came to our house and killed my husband Tomas. He took the "
          "diamond Tomas was cutting, the last thing of value we had. He hides down there in the old catacombs, "
          "beyond the dead and the priests' traps. The guards won't go near the place. Will you bring Tomas's "
          "diamond back to me?",
          when=q.at(MAIN, 0), ask=True,
          do=[A.stage(MAIN, 1), q.journal(J_MAIN)],
          else_=[q.tell(maren, "Then I'll sit here and wait for the dead to take me too.")]),
    q.say("There's an old chapel off the first crypt. The priests kept a black book there with the names of the dead. "
          "Will you bring it to me, so I can write Tomas's name in it?",
          when=q.at(SIDE, 0), ask=True,
          do=[A.stage(SIDE, 1), q.journal(J_SIDE)],
          else_=[q.tell(maren, "I understand. The chapel is no place for the living.")]),
    q.say("He still lives, doesn't he? I can see it in your face.", when=q.at(MAIN, 1, has=DIAMOND)),
    q.say("Is Silas Vane dead yet? I can't sleep while he lives!", when=q.at(MAIN, 1)),
], pic="MaidenPic4", title="Widow Maren")
q.on_death(boss, [A.stage(MAIN, 2), q.note("Silas Vane is dead. His hoard lies in the room beyond his lair.")])
q.start([q.journal("Speak to Widow Maren at the gate of the catacombs.")])
M.sign("camp", "THE OLD CATACOMBS. Closed by order of the town guard.", 2.0, 1.4)

m = M.m                                   # tests/server_smoke.py reads the spec as m
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out", "trapdemo", NAME)
if cleared: print(f"{NAME}: cleared from the passages' mouths: {', '.join(cleared)}")
M.finish(None if out == "-" else out)
