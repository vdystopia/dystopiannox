"""TrapDemo 03: The Serpent Steps (map TrapDem03; kit/trapdemo.py Mission). A jungle temple of the serpent priests,
raced for by two relic hunters.

The story
- The hook: Nala the scout has camped in the outer court with her dig. She and her brother Tavin came for the
  Serpent's Eye, the great emerald of the jade idol in the inner shrine; Tavin went in ahead and never came back. At
  dawn the ranger Garet Hawkeye, a rival hunter, went up the Steps after the same stone and holds the stepped hall
  before the shrine. The priests left the temple full of traps: arrow slits, spike floors, pits, tripwires.
- Main quest (the Serpent's Eye): get past the priests' traps and Garet Hawkeye and bring the Eye (an Emerald) back
  to Nala. She pays in gold.
- Side quest (Tavin's map case): Tavin's case lies in a side vault off the chapel, behind a racing gate, his bones
  beside it; he did not make it. Nala gives his potions of haste for it.
- The traps, in the order a player meets them: lane plates at the serpent gate; plates that open the floor ahead
  into the chapel (a fall lands back in the gate room); the racing gate before the side vault (triggers taught where a
  mistake is cheap); the spike wave to the scriptorium; the lane hall, eight rows of plates and their arrow traps, to
  the priests' crypt; stepping stones over a rotten floor before Garet's hall. The star pool off the scriptorium is
  the rest before the hard half.

    py mapgen/designs/trapdemo03.py [out_dir|-]
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from kit.trapdemo import Mission
from kit.quests import A
from kit.trapdemo_dress import kit_camp, open_spot, wall_spot, chest
from kit.setpieces import healing_well, ensure_blends, PAD
from kit.layout import square_px, square_tile

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "TrapDem03"
M = Mission(NAME, "The Serpent Steps", "temple", seed=3, ambient=(105, 110, 95),
            description="[env:castle] TrapDemo 03, The Serpent Steps: a serpent priests' temple of arrow slits, spike "
                        "floors, pits and tripwires, raced for by two relic hunters. Generated by Claude.")
M.room("court", (14, 12), role="camp", start=True)
M.room("gate", (12, 12), role="guard", kind="guardroom")
M.room("chapel", (16, 14), role="shrine", kind="chapel")
M.room("sidevault", (12, 12), role="store", kind="treasury")
M.room("scriptorium", (14, 12), role="room", kind="library")
M.room("pool", (14, 12), role="room", kind="mana_room")
M.room("crypt", (14, 12), role="crypt", kind="crypt")
M.room("steps", (18, 14), role="boss", kind="throne_room")
M.room("shrine", (12, 12), role="vault", kind="shrine")
M.link("court", "gate", trap=("arrow", 0))                   # lane plates: the serpent gate
M.link("gate", "chapel", trap=("pit", 2))                    # look before you leap: plates that open the floor
M.link("chapel", "sidevault", trap=("trigger", 5))           # race the gate: the side quest's price
M.link("chapel", "scriptorium", trap=("spike", 2))           # the wave
M.link("scriptorium", "pool", length=6)                      # the rest before the hard half
M.link("scriptorium", "crypt", trap=("arrow", 5))            # the lane hall: eight rows of plates
M.link("crypt", "steps", trap=("pit", 5))                    # stepping stones on a rotten floor
M.link("steps", "shrine", length=5)
M.layout()
court = M.rooms.pop("court")                                 # the court is laid by the camp kit, the rest by the room kit
M.dress()
M.rooms = {"court": court, **M.rooms}
camp = kit_camp(M, "court", trade="dig", sleepers=2, tents=1, loot=[("Gold", {"Amount": 25}), "RedPotion", "CurePoisonPotion"])
M.start_at("court")

# ---- the plot's things, loot ------------------------------------------------------------------------------------
sw, sh = M.rooms["shrine"]["size"]
eye = M.item("shrine", "Emerald", *open_spot(M, "shrine", sw / 2, sh / 2 - 0.4))   # before the altar
for k, wall in enumerate(("NE", "NW")):                    # the priests' offerings, a chest by each back wall
    spot = wall_spot(M, "shrine", (wall,), clear=1.3)
    if spot: chest(M, "shrine", *spot, [("Gold", {"Amount": 90 + 40 * k}), "RedPotion"])
va, vb = open_spot(M, "sidevault", 6, 6, clear=1.1)
case = M.item("sidevault", "AutoMap", va, vb)
for t, da_, db_ in (("Skull", 0.6, 0.5), ("ArmBone", -0.5, 0.6), ("LegBone", 0.4, -0.6)):  # Tavin, who did not make it
    M.m.obj_px(t, *M.at("sidevault", va + da_, vb + db_))
pw, ph = M.rooms["pool"]["size"]
wa, wb = open_spot(M, "pool", pw / 2, ph / 2, clear=2.0)    # the star pool: the healing well (kit/setpieces.py)
healing_well(M.m, *M.at("pool", wa, wb))
for (i, j) in M.parts["pool"].squares:                     # on its own paving, a curb round it
    a_, b_ = M.room_ab("pool", *square_px(i + 0.5, j - 0.5))
    if abs(a_ - wa) < 2.0 and abs(b_ - wb) < 2.0: M.m.floor[square_tile(i, j)] = PAD
ensure_blends(M.m)
for s_ in (-1, 1):                                          # urns either side of it
    M.m.obj_px("StatueVase2S", *M.at("pool", wa + 1.45 * s_, wb + 0.2))
M.m.obj_px("Sign1", *M.at("pool", wa - 1.4, wb + 1.6))     # a sign with no text by a well reads "Magical Well"
for k, t in enumerate(("RedPotion", "CurePoisonPotion")):
    M.m.obj_px(t, *M.at("pool", wa + 0.6 + 0.45 * k, wb - 1.5))
cw, ch = M.rooms["crypt"]["size"]
spot = wall_spot(M, "crypt", ("NE", "NW", "SE"), clear=1.45) or open_spot(M, "crypt", cw / 2, ch / 2, clear=1.2)
chest(M, "crypt", *spot, [("Gold", {"Amount": 120}), "RedPotion", "BluePotion", "PoisonProtectPotion"])

# ---- life -------------------------------------------------------------------------------------------------------
M.monsters("gate", {"Urchin": 3})
M.monsters("chapel", {"Spider": 2, "Urchin": 1})
M.monsters("sidevault", {"Scorpion": 1})
M.monsters("scriptorium", {"SpittingSpider": 2, "Spider": 1})
M.monsters("crypt", {"Scorpion": 2, "BlackWidow": 1})
boss = M.boss("steps", "B6")
nala = M.person("court", "Con07B", "Shari", "Nala", *M.room_ab("court", *camp["leader"]), face=camp["fire"],
                pic="MaidenPic6", title="Nala the Scout")

# ---- the story --------------------------------------------------------------------------------------------------
q = M.q
MAIN, SIDE = "eye", "mapcase"
IDOL = "Bring the Serpent's Eye from the inner shrine to Nala."
CASE = "Find Tavin's map case in the side vault off the chapel."
q.talker(nala, [
    q.say("The Serpent's Eye! I can hardly believe it! Garet Hawkeye beaten at his own game. Here is your gold, as "
          "promised. Every coin of it!",
          when=q.when(has="Emerald", not_=f"{MAIN}done"),
          do=[A.take("Emerald"), A.gold(450), A.stage(MAIN, 3), A.flag(f"{MAIN}done"), q.done(IDOL)]),
    q.say("That's Tavin's map case. So he's gone. Thank you for bringing it out of there. Take these potions. "
          "They were his.",
          when=q.when(has="AutoMap", not_=f"{SIDE}done"),
          do=[A.take("AutoMap"), A.give("HastePotion", 2), A.flag(f"{SIDE}done"), q.done(CASE)],
          mood="quiet, holding back grief"),
    q.say("A thousand thanks, kind stranger.", when=q.at(MAIN, 3)),
    q.say("Garet is dead? Ha! Then the Eye is ours. Go on, fetch it!", when=q.at(MAIN, 2)),
    q.say("Go on! Every hour we wait, Garet gets closer to the Eye.", when=q.at(MAIN, 1)),
    q.say("Keep your voice down! Garet Hawkeye and his bow went up the Steps at dawn. He's after the Serpent's Eye, "
          "the great emerald of the jade idol in the inner shrine. So am I.\n\nMy brother Tavin went in ahead of us "
          "and never came back. The priests filled the temple with traps -- arrow slits, spiked floors, pits. I "
          "can't do it alone.\n\nWill you beat Garet to the Eye? I'll pay you well.",
          ask=True,
          do=[A.stage(MAIN, 1), q.journal(IDOL), q.journal(CASE)],
          else_=[q.tell(nala, "Then Garet gets the Eye, and we all go home poor.")]),
], pic="MaidenPic6", title="Nala the Scout")
q.on_death(boss, [A.stage(MAIN, 2), q.note("Garet Hawkeye is dead. The way to the inner shrine is open.")])
q.on_pickup("Emerald", [q.note("The Serpent's Eye is cold to the touch, and heavier than it looks.")])
q.start([q.journal("Speak to Nala the scout in the outer court.")])
M.sign("court", "THE SERPENT STEPS. Thieves turn back.", 2.0, 1.2)

m = M.m                                   # tests/server_smoke.py reads the spec as m
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out", "trapdemo", NAME)
M.finish(None if out == "-" else out)
