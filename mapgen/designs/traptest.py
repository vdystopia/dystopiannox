"""TrapTest: one of each trap object in a plain stone hall, for the engine facts behind the trap kit
(tests/traps_e2e/run.py traptest: a real player stood in each trap by a probe script that logs what it did).

Not a map to play: a test bench (designs/status.json "test"). Stations along the hall, each at TESTS[k]["at"]:
spike carpet on a clock, periodic spikes, flames on a clock, a spike block moved across the hall by the script,
rotating spikes, arrow traps of both kinds pulsed on a clock, a fixed sentry globe, a pit and crumbling floor
(falling to a sealed cell), a wall toggled by the script, a push, a glyph, skull guns, a fire grate flame, a rolling
boulder, and a flame line to jump over (the e2e input walks east and jumps).

    py mapgen/designs/traptest.py [out_dir|-]
"""
import json, math, os, random, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from nox import Spec, SOLO, CELL
from kit.dungeon import Dungeon
from kit.traps import Traps

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "TrapTest"
m = Spec(NAME, summary="Trap test", description="[env:castle] One of each trap object, for the trap kit's engine "
         "tests. Generated by Claude.", author="vdystopia (generated by Claude)", version="0.1", date="2026",
         type=SOLO, minPlayers=1, maxPlayers=1)
m.d["nxz"] = False
m.d["ambient"] = [200, 200, 200]
m.loot = False
m.heal_wells = False
rng = random.Random(1)
d = Dungeon(m, rng, wall="DungeonStone", floor="GreenBrick")
HALL = d.box("hall", 100, 0, 84, 12)            # 84 squares along i, 12 across j
CELLR = d.box("cell", 100, -30, 10, 10)         # the pit cell: sealed, where fallers land
d.apply()
T = Traps(m, prefix="TT")
TESTS = []


def station(name, a, b=6.0, **info):
    x, y = HALL.at(a, b)
    TESTS.append(dict(name=name, at=[round(x, 1), round(y, 1)], **info))
    return x, y


def carpet(type_, a0, b0, n, step=11.5, enabled=True):
    """A square carpet of n x n small spikes, `step` px apart, its first corner at (a0, b0) in the hall."""
    x0, y0 = HALL.at(a0, b0)
    return [T.obj(type_, x0 + i * step, y0 + j * step, enabled=enabled) for i in range(n) for j in range(n)]


# 1. a spike carpet on a clock: up the first second of every two
x, y = station("spike_clock", 4.0, frames=120)
T.group("G_spike", carpet("Spike", 3.0, 5.0, 6))
T.clock("C_spike", "G_spike", 60, [(0, 30)])
# 2. periodic spikes (cycle by themselves)
station("periodic", 9.0, frames=120)
carpet("PeriodicSpike", 8.0, 5.0, 6)
# 3. flames on a clock
station("flame_clock", 14.0, frames=120)
x, y = HALL.at(14.0, 6.0)
T.group("G_flame", [T.obj("Flame", x + dx, y) for dx in (-12, 0, 12)])
T.clock("C_flame", "G_flame", 60, [(0, 30)])
# 4. a spike block moved across the hall by the script (there and back, 4 px a frame)
station("block", 19.0, frames=150)
bx0, by0 = HALL.at(19.0, 1.5)
bx1, by1 = HALL.at(19.0, 10.5)
blk = T.obj("SpikeBlock", bx0, by0)
T.mover("M_block", [blk], [(bx0, by0), (bx1, by1)], speed=4.0, mode="pingpong", pause=15)
# 5. rotating spikes standing still
station("rotating", 24.0, frames=60)
T.obj("RotatingSpikes", *HALL.at(24.0, 6.0))
# 6. arrow traps (the type fixes the facing: ArrowTrap1 shoots SE, down the hall; ArrowTrap2 SW, across it), on
station("arrow1", 30.0, frames=90)
T.obj("ArrowTrap1", *HALL.at(26.5, 6.0))
station("arrow2", 33.0, b=4.0, frames=90)
T.obj("ArrowTrap2", *HALL.at(33.0, 11.3))
# 7. a sentry globe, beam fixed across the hall toward the SW wall (3pi/4); the hero one square beside the beam
station("sentry", 37.0, b=4.0, frames=60)
T.obj("SentryGlobe", *HALL.at(36.0, 11.0), xfer={"BasePosRadian": 2.35619, "RotateSpeed": 0.0, "CurrentPosRadian": 0.0})
# 8. a pit and 9. crumbling floor, both falling into the sealed cell
fx, fy = CELLR.centre
station("pit", 40.0, frames=60)
T.obj("Pit", *HALL.at(40.0, 6.0), xfer={"UnknownScriptHandler": "", "FallX": int(fx), "FallY": int(fy),
                                       "ScriptTime1": 0, "ScriptTimeout": 0, "ScriptActivated": 0})
station("crumble", 45.0, frames=90)
for i in range(3):
    for j in range(3):
        x, y = HALL.at(44.0 + i, 5.0 + j)
        T.obj("PitCrumblingFloor", x + 16, y + 16, xfer={"UnknownScriptHandler": "", "FallX": int(fx), "FallY": int(fy),
                                                        "ScriptTime1": 0, "ScriptTimeout": 4, "ScriptActivated": 0})
# 10. a wall pillar the script opens and closes (on a clock in the probe)
wa, wb = 50, 3
from kit.layout import point_cell
WALL = point_cell(HALL.i0 + wa, HALL.j0 + wb)
m.wall(WALL[0], WALL[1], "DungeonStone", facing=2, secret="closed")
station("wall", 51.0, frames=60, wall=list(WALL))
# 11. a push (the probe applies it)
station("push", 55.0, frames=60)
# 11b. a pressure plate calling the script (a flame pulse), and a lever (the probe stands the hero on each)
station("plate", 57.0, b=3.0, frames=60)
px_, py_ = HALL.at(57.0, 3.0)
T.group("G_pflame", [T.obj("Flame", *HALL.at(57.0, 9.0), enabled=False)])
T.plate("TestPlate", px_, py_, acts=[T.act("log", text="plate pressed"), T.act("pulse", "G_pflame", frames=30)],
        release=[T.act("log", text="plate released")])
station("lever", 57.0, b=9.5, frames=90)
T.lever("TestLever", "FloorLever1", *HALL.at(57.0, 10.0), acts=[T.act("log", text="lever on")],
        release=[T.act("log", text="lever off")])
# 12. a glyph with a fireball
station("glyph", 59.0, frames=60)
gx, gy = HALL.at(59.0, 6.0)
T.obj("Glyph", gx, gy, xfer={"Angle": 0, "TargX": gx, "TargY": gy, "Spells": ["SPELL_FIREBALL"]})
# 13. skull guns (wall decoration that shoots?) facing the hall, on
station("skull", 63.0, frames=120)
for k, t in enumerate(("Skull1", "Skull2", "Skull3", "Skull4")):
    T.obj(t, *HALL.at(62.0 + k * 0.7, 0.4))
# 14. a fire grate's flame, 15. a rolling boulder
station("grate", 67.0, frames=60)
T.obj("FireGrate", *HALL.at(67.0, 6.0))
T.obj("FireGrateFlame", *HALL.at(67.0, 6.0))
T.obj("RollingBoulder", *HALL.at(70.0, 2.0))
# 16. the jump: an always-on line of flames across the hall at a = 75.6, the hero set 2 squares before it
JUMP_LINE = []
for k in range(12):
    JUMP_LINE.append(T.obj("Flame", *HALL.at(75.6, 0.6 + k)))
jump_from = HALL.at(73.6, 6.0)
# a plate on the way to the flames: the jump passes over it, the walk presses it
T.plate("WalkPlate", *HALL.at(74.6, 6.0), acts=[T.act("log", text="walkplate pressed")],
        release=[T.act("log", text="walkplate released")])
# 17. the run (speed, a running jump) from a = 40 at b = 9.5 (clear of the other stations' objects), and a lever to click
run_from = HALL.at(38.0, 9.8)
lever_at = HALL.at(81.5, 6.0)
lever_from = HALL.at(80.0, 6.0)
T.lever("ClickLever", "FloorLever1", *lever_at, acts=[T.act("log", text="clicklever on")],
        release=[T.act("log", text="clicklever off")])

m.obj_px("PlayerStart", *HALL.at(1.5, 6.0))
T.attach()

out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out")
INFO = dict(tests=TESTS, jump_from=list(jump_from), run_from=list(run_from), lever_from=list(lever_from),
            lever_at=list(lever_at), jump_line=[T.objects[n]["x"] for n in JUMP_LINE[:1]],
            cell=[fx, fy], wall=list(WALL))
if out_dir != "-":
    os.makedirs(out_dir, exist_ok=True)
    lines = m.build(out_dir)
    T.write(out_dir)
    json.dump(INFO, open(os.path.join(out_dir, f"{NAME}.tests.json"), "w"), indent=1)
    print("\n".join(l for l in lines if l.startswith(("OK", "ERROR", "CHECK", "SCRIPTS"))))
print(f"{NAME}: {len(TESTS)} stations, {len(T.objects)} trap objects")
