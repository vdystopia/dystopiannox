"""TrapDemo 06: Thornhold Keep (map TrapDem06; kit/trapdemo.py Mission). A keep whose garrison has turned on its lord.

The story
- The hook: Castellan Theodric holds the keep's outer gate with what is left of his household. The High Warden
  Aurelian took the Amulet of Manipulation from the treasury, and with it the garrison does his bidding: the guards,
  archers and swordsmen of Thornhold now hold the keep against its castellan. The keep's builders laid its halls
  with arrow slits, plates, beams and spike blocks against just such a day.
- Main quest (the Amulet): fight up through the keep past its defences, put down the High Warden in the throne room
  and bring the amulet from the chapel's altar beyond it. Theodric pays in gold on the way back, and the spell on
  his men breaks.
- Side quest (the armoury's key): Theodric dropped the armoury's key in the gatehouse cellar when his men fled; the
  cellar lies beyond a wall that a button slides open for seven seconds, spikes before it. He gives potions for
  it.
- The traps, in the order a player meets them: the click and the pause at the gate (arrows two squares ahead of a
  plate); the cellar's race to the gate; the snapping jaws to the armoury (a dead end with its arms); two beams in
  turn before the great hall; then the hard half: three gates of beams to the warden's quarters, run from their
  plates, and the lane hall of plates and arrows before the throne room.

    py mapgen/designs/trapdemo06.py [out_dir|-]
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from kit.trapdemo import Mission
from kit.trapdemo_dress import camp, clear_mouths, start_spot, free_spot, extra
from kit.quests import A

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "TrapDem06"
M = Mission(NAME, "Thornhold Keep", "castle", seed=6, ambient=(120, 115, 105),
            description="[env:castle] TrapDemo 06, Thornhold Keep: a keep whose garrison holds it against its own "
                        "castellan, its halls laid with arrow slits, plates, beams and spike blocks. Generated by "
                        "Claude.")
KEEP = "dunmir"                     # the castle's pieces (Dun Mir's hangings and stands) for the keep's rooms
M.room("camp", (14, 12), role="camp", start=True, closed=("NE", "NW"))
M.room("gatehouse", (14, 12), role="guard", kind="guardroom", style=KEEP)
M.room("cellar", (12, 12), role="store", kind="cellar", style=KEEP)
M.room("barracks", (16, 14), role="guard", kind="barracks", style=KEEP)
M.room("armoury", (14, 12), role="store", kind="gear_store", style=KEEP)   # the room kit's armoury
M.room("hall", (18, 14), role="room", kind="great_hall", style=KEEP)
M.room("store", (12, 12), role="store", kind="storeroom", style=KEEP)
M.room("quarters", (14, 12), role="room", kind="solar", style=KEEP)
M.room("throne", (18, 16), role="boss", kind="throne_room", style=KEEP, closed=("NW",))
M.room("chapel", (14, 12), role="vault", kind="chapel", style=KEEP)
M.link("camp", "gatehouse", trap=("arrow", 1))                # the click and the pause: the way in
M.link("gatehouse", "cellar", trap=("trigger", 5))            # race the gate: the side quest's price
M.link("gatehouse", "barracks", length=6)
M.link("barracks", "armoury", trap=("block", 1))              # snapping jaws: blocks taught in a dead end
M.link("barracks", "hall", trap=("sentry", 1))                # two beams in turn
M.link("hall", "store", length=6)                             # the rest: the keep's stores
M.link("hall", "quarters", trap=("sentry", 7))                # run the gates (hard)
M.link("quarters", "throne", trap=("arrow", 5))               # the lane hall (hard)
M.link("throne", "chapel", length=5)
M.layout()
n0 = len(M.m.d["objects"])
M.dress()
cleared = clear_mouths(M, M.m.d["objects"][n0:])
camp(M, "camp")
M.start_at("camp", *start_spot(M, "camp"))
# the cellar's kegs and sacks along its back walls, the barracks' racks on its NE wall (the room kit's bunks line
# its front)
w, h = M.rooms["cellar"]["size"]
extra(M, "cellar", [("PiledBarrels1", 1.4, h / 2 + 1.5), ("PiledBarrels2", 1.4, h / 2 - 1.5),
                    ("BarrelSteel1", w / 2 - 2.0, h - 1.2), ("SackChestLarge1", w / 2 - 3.3, h - 1.2),
                    ("WaterBarrel", 1.3, 1.6)])
w, h = M.rooms["barracks"]["size"]
extra(M, "barracks", [("TraderPoleArm1", w / 2 - 2.5, h - 0.9), ("OutdoorTraderArmorRack1", w / 2 + 2.5, h - 0.9),
                      ("TraderPoleArm2", 0.9, h / 2 + 2.5), ("OutdoorTraderArmorRack3", 0.9, h / 2 - 2.5),
                      ("TraderPoleArm3", 2.6, h - 0.9), ("Chest4", w - 4.0, h - 1.0, {"items": ["RedPotion"]})],
      clear=1.2)

# ---- life -------------------------------------------------------------------------------------------------------
M.monsters("gatehouse", {"GruntAxe": 2, "Archer": 1})
M.monsters("cellar", {"GruntAxe": 2})
M.monsters("barracks", {"Swordsman": 2, "GruntAxe": 2})
M.monsters("armoury", {"Archer": 2, "Swordsman": 1})
M.monsters("hall", {"Swordsman": 2, "Archer": 2, "OgreBrute": 1})
M.monsters("quarters", {"Swordsman": 2, "OgreBrute": 1, "Troll": 1})
boss = M.boss("throne", "B10")

AMULET, KEY = "AmuletofManipulation", "GoldKey"
w, h = M.rooms["chapel"]["size"]
M.item("chapel", AMULET, *free_spot(M, "chapel", w / 2, h - 3.0))
w, h = M.rooms["cellar"]["size"]
M.item("cellar", KEY, *free_spot(M, "cellar", w - 3.0, h - 3.0, clear=1.4))
# potions where a player stops between stages: the barracks after the gate, the keep's stores, the quarters
for rid, n in (("barracks", 2), ("store", 4), ("quarters", 2)):
    w, h = M.rooms[rid]["size"]
    pa, pb = free_spot(M, rid, 2.0, 2.0, clear=1.2)
    for k in range(n):
        M.put(rid, "RedPotion", pa + 0.45 * k, pb, clear=2.4)
theodric = M.person("camp", "Con02a", "Mayor_Theogrin", "Theodric", pic="TheogrinPic", title="Castellan Theodric")

# ---- the story --------------------------------------------------------------------------------------------------
q = M.q
MAIN, SIDE = "amulet", "armourykey"
J_MAIN = "Bring the Amulet of Manipulation from the chapel of Thornhold Keep."
J_SIDE = "Find the armoury's key in the cellar under the gatehouse."
q.talker(theodric, [
    q.say("Thanks again, brave Adventurer! Thornhold is in your debt.", when=q.at(MAIN, 3)),
    q.say("The amulet! I can feel the spell breaking already. My men will know their lord again! Here's your reward "
          "-- 700 in gold!",
          when=q.at(MAIN, 2, has=AMULET),
          do=[A.take(AMULET), A.gold(700), A.stage(MAIN, 3), q.done(J_MAIN)]),
    q.say("My key! Now we can arm ourselves properly. Take these potions. You'll need them more than we do.",
          when=q.at(SIDE, 1, has=KEY),
          do=[A.take(KEY), A.give("RedPotion", 3), A.stage(SIDE, 3), q.done(J_SIDE)]),
    q.say("Thank goodness, help at last!\n\n"
          "The High Warden Aurelian has lost his mind. He took the Amulet of Manipulation from the treasury, and now "
          "the whole garrison does his bidding. My own men turned their swords on me! He keeps the amulet on the "
          "altar of the chapel, beyond the throne room at the top of the keep. Will you bring it back to me and break "
          "his hold on Thornhold?",
          when=q.at(MAIN, 0), ask=True,
          do=[A.stage(MAIN, 1), q.journal(J_MAIN)],
          else_=[q.tell(theodric, "Then go, and quickly. Aurelian's men will come for this gate soon enough.")]),
    q.say("One more thing. When we fled the gatehouse I dropped the armoury's key in the cellar below it. Will you "
          "look for it?",
          when=q.at(SIDE, 0), ask=True,
          do=[A.stage(SIDE, 1), q.journal(J_SIDE)],
          else_=[q.tell(theodric, "Very well. We'll hold the gate with what we have.")]),
    q.say("The High Warden still lives. I can hear his men on the walls.", when=q.at(MAIN, 1, has=AMULET)),
    q.say("Hurry! I don't know how long we can hold the gate!", when=q.at(MAIN, 1)),
], pic="TheogrinPic", title="Castellan Theodric")
q.on_death(boss, [A.stage(MAIN, 2), q.note("High Warden Aurelian is dead. The chapel lies open beyond the throne room.")])
q.start([q.journal("Speak to Castellan Theodric at the outer gate.")])
M.sign("camp", "THORNHOLD KEEP. By order of the High Warden, the gate is shut.", 2.0, 1.4)

m = M.m                                   # tests/server_smoke.py reads the spec as m
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out", "trapdemo", NAME)
if cleared: print(f"{NAME}: cleared from the passages' mouths: {', '.join(cleared)}")
M.finish(None if out == "-" else out)
