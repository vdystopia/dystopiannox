"""TrapDemo 01: The Reliquary of Saint Varo (map TrapDem01; kit/trapdemo.py Mission). A crypt under a ruined abbey.

The story
- The hook: Brother Aldous, a scholar of the abbey, has camped in the crypt's entry vault with what is left of his
  expedition. The saint's reliquary lies in the sanctum below; grave-robbers under the necromancer Lord Mortivane went
  down three days ago and the dead have been walking since. The old monks warded the way with traps.
- Main quest (the Reliquary): reach the sanctum past the monks' traps, put down Mortivane in the bone hall and bring
  the reliquary back to Aldous, who pays and blesses the player.
- Side quest (Pell's satchel): Aldous's apprentice Pell ran ahead and never came back; his satchel with the abbey's
  map is in the ossuary's store, beyond a passage of fire. Aldous gives a staff for it.
- The traps, in the order a player meets them: a spike field on a clock at the way down; the ossuary's fire passage
  to the store; a hard passage to the gallery; the shrine's lever gate; the long run into the bone hall.

    py mapgen/designs/trapdemo01.py [out_dir|-]
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from kit.trapdemo import Mission
from kit.quests import A

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "TrapDem01"
M = Mission(NAME, "The Reliquary of Saint Varo", "crypt", seed=1,
            description="[env:castle] TrapDemo 01, The Reliquary of Saint Varo: a crypt under a ruined abbey, warded "
                        "by its monks' traps; a necromancer's band went down first. Generated by Claude.")
M.room("camp", (14, 12), role="camp", start=True)
M.room("ante", (14, 12), role="guard", kind="guardroom")
M.room("ossuary", (16, 14), role="crypt", kind="ossuary")
M.room("store", (12, 10), role="store", kind="storeroom")
M.room("gallery", (16, 12), role="guard", kind="mausoleum")
M.room("shrine", (14, 12), role="shrine", kind="shrine")
M.room("hall", (18, 14), role="boss", kind="hall")
M.room("sanctum", (12, 10), role="vault", kind="treasury")
M.link("camp", "ante", trap=("spike", 0))                     # one field on a clock: the way down
M.link("ante", "ossuary", length=6)
M.link("ossuary", "store", trap=("flame", 2))                 # the fire wave: the side quest's price
M.link("ossuary", "gallery", trap=("auto", "standard"))
M.link("gallery", "shrine", trap=("auto", "hard"))
M.link("shrine", "hall", trap=("spike", 7))                   # the spike gate: the shrine's lever
M.link("hall", "sanctum", length=5)
M.layout()
M.dress()
M.start_at("camp")

# ---- life -------------------------------------------------------------------------------------------------------
M.monsters("ante", {"Skeleton": 2})
M.monsters("ossuary", {"Zombie": 3})
M.monsters("store", {"Bat": 2})
M.monsters("gallery", {"Skeleton": 2, "SkeletonLord": 1})
M.monsters("shrine", {"Ghost": 2})
boss = M.boss("hall", "B4")
relic = M.item("sanctum", "MayorsScepter")
satchel = M.item("store", "TreasureBag", 4, 4)
M.m.obj_px("RedPotion", *M.at("store", 6, 2))
aldous = M.person("camp", "Wiz02A", "TowerNPC", "Aldous", pic="ArchivistPic", title="Brother Aldous")

# ---- the story --------------------------------------------------------------------------------------------------
q = M.q
MAIN, SIDE = "relic", "satchel"
q.talker(aldous, [
    q.say("The reliquary. You found it. Saint Varo forgive us both for what it cost to bring it up. Take this, and "
          "my blessing. The abbey owes you more than gold.",
          when=q.at(MAIN, 2, has="MayorsScepter"),
          do=[A.take("MayorsScepter"), A.gold(400), A.give("RedPotion", 3), A.stage(MAIN, 3),
              q.done("Bring Saint Varo's reliquary up from the sanctum.")]),
    q.say("Pell's satchel. Then he is gone. The map in it is the abbey's last. Take my old staff for your trouble.",
          when=q.when(has="TreasureBag", not_=f"{SIDE}done"),
          do=[A.take("TreasureBag"), A.give("LesserFireballStaff"), A.flag(f"{SIDE}done"),
              q.done("Find Pell's satchel in the ossuary's store.")]),
    q.say("Mortivane is down there still, in the bone hall before the sanctum. The reliquary lies beyond him.",
          when=q.at(MAIN, 1)),
    q.say("Thank the saint, a live face. I am Aldous, of the abbey above. Three days ago a necromancer called "
          "Mortivane went down to the sanctum for Saint Varo's reliquary, and the dead have walked since. The monks "
          "warded the way with traps. Will you go down and bring the reliquary back?",
          ask=True,
          do=[A.stage(MAIN, 1), q.journal("Bring Saint Varo's reliquary up from the sanctum."),
              q.journal("Find Pell's satchel in the ossuary's store.")],
          else_=[q.tell(aldous, "Then sit by the fire with me and wait for the dead to come up.")]),
], pic="ArchivistPic", title="Brother Aldous")
q.on_death(boss, [A.stage(MAIN, 2), q.note("Lord Mortivane is dead. The sanctum lies open.")])
q.start([q.journal("Speak to Brother Aldous at the camp in the entry vault.")])
M.sign("camp", "THE CRYPT OF SAINT VARO. The monks' wards still hold below.", 2.0, 1.2)

m = M.m                                   # tests/server_smoke.py reads the spec as m
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out", "trapdemo", NAME)
M.finish(None if out == "-" else out)
