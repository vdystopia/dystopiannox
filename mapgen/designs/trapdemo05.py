"""TrapDemo 05: The Vault of Night (map TrapDem05; kit/trapdemo.py Mission). A tomb of the Land of the Dead.

The story
- The hook: Ingrid, a hunter of the undead, has camped at the upper gate of the Vault of Night, the tomb where the old
  Necromancers sealed the Blue Idol, one of the two keys of the Lich's Hall. The archmage Vael the Unbound has broken
  in for it and the dead are awake. The Necromancers warded the way with beams, blades and runes.
- Main quest (the Blue Idol): go down past the wards, put down Vael in his hall and bring the Idol up from the vault
  beneath the beams. Ingrid pays in gold on the way back.
- Side quest (Hagen's key): Ingrid's partner Hagen went into the ossuary and never came out; his silver key lies with
  his bones beyond a passage of falling stars. Ingrid gives his amulet for it.
- The traps, in the order a player meets them: a revolving door of blades at the way down (cheap to get wrong); the
  ossuary's falling stars; a lone beam on a clock before the coven's stores (the beams taught where nothing presses);
  the walking gap to the mana room; then the hard half: the runes and their warden, the sliding doors of blades, and
  the crossing beams before Vael's hall.

    py mapgen/designs/trapdemo05.py [out_dir|-]
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from kit.trapdemo import Mission
from kit.trapdemo_dress import camp, clear_mouths, start_spot, free_spot, extra
from kit.quests import A

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "TrapDem05"
M = Mission(NAME, "The Vault of Night", "lotd", seed=5, ambient=(90, 90, 110),
            description="[env:castle] TrapDemo 05, The Vault of Night: a tomb of the Land of the Dead where the "
                        "Necromancers sealed the Blue Idol, warded by beams, blades and runes; an archmage broke in "
                        "first. Generated by Claude.")
LOTD = "lotd"
M.room("camp", (14, 12), role="camp", start=True)
M.room("gate", (14, 12), role="guard", kind="crypt", style=LOTD)
M.room("ossuary", (14, 12), role="crypt", kind="ossuary", style=LOTD)
M.room("library", (16, 14), role="room", kind="library", style=LOTD)
M.room("coven", (14, 12), role="store", kind="coven", style=LOTD)
M.room("mana", (16, 14), role="shrine", kind="mana_room", style=LOTD)
M.room("crypt", (16, 12), role="crypt", kind="crypt", style=LOTD)
M.room("mausoleum", (16, 14), role="guard", kind="mausoleum", style=LOTD)
M.room("hall", (18, 16), role="boss", kind="throne_room", style=LOTD)
M.room("vault", (12, 12), role="vault", kind="treasury", style=LOTD)
M.link("camp", "gate", trap=("blade", 3))                     # the revolving door: the way down
M.link("gate", "ossuary", trap=("spell", 3))                  # falling stars: the side quest's price
M.link("gate", "library", length=6)
M.link("library", "coven", trap=("sentry", 0))                # one beam on a clock: the beams taught
M.link("library", "mana", trap=("sentry", 3))                 # the walking gap
M.link("mana", "crypt", trap=("spell", 5))                    # the runes and their warden (hard)
M.link("crypt", "mausoleum", trap=("blade", 5))               # the sliding doors (hard)
M.link("mausoleum", "hall", trap=("sentry", 5))               # crossing beams before Vael's hall (hard)
M.link("hall", "vault", length=5)
M.layout()
n0 = len(M.m.d["objects"])
M.dress()
cleared = clear_mouths(M, M.m.d["objects"][n0:])
camp(M, "camp")
M.start_at("camp", *start_spot(M, "camp"))
# the ossuary's skull pillars along its back walls (the room kit lays its bones and coffins)
w, h = M.rooms["ossuary"]["size"]
extra(M, "ossuary", [("LOTDTombstoneSkulls1", w / 2 - 2.5, h - 1.6), ("LOTDTombstoneSkulls2", w / 2 + 2.5, h - 1.6),
                     ("LOTDTombstoneSkulls1", 1.6, h / 2 + 2.0), ("LOTDTombstoneSkulls2", 1.6, h / 2 - 2.0)])
# the mana room's obelisk in the middle, flaming skulls either side, their light on the crystals
w, h = M.rooms["mana"]["size"]
extra(M, "mana", [("LOTDManaObelisk", w / 2, h / 2 + 0.5), ("LOTDFlamingSkullsStatic", w / 2 - 2.6, h / 2 + 0.5),
                  ("LOTDFlamingSkullsStatic", w / 2 + 2.6, h / 2 + 0.5)], reach=1.5)

# ---- life -------------------------------------------------------------------------------------------------------
M.monsters("gate", {"Bat": 2, "Skeleton": 2})
M.monsters("ossuary", {"Zombie": 2, "Bat": 2})
M.monsters("library", {"Skeleton": 2, "Ghost": 1})
M.monsters("coven", {"Ghost": 2})
M.monsters("mana", {"Skeleton": 2, "SkeletonLord": 1, "Ghost": 1})
M.monsters("crypt", {"Zombie": 2, "SkeletonLord": 1, "Shade": 1})
M.monsters("mausoleum", {"SkeletonLord": 2, "Ghost": 2, "Shade": 1})
boss = M.boss("hall", "B1")

IDOL, KEY = "BlueOrbKeyOfTheLich", "SilverKey"
w, h = M.rooms["vault"]["size"]
idol = M.item("vault", IDOL, *free_spot(M, "vault", w / 2, h / 2 - 1.0))
# Hagen's bones by the ossuary's far wall, his key among them
w, h = M.rooms["ossuary"]["size"]
ka, kb = free_spot(M, "ossuary", w - 3.2, h - 3.0, clear=1.6)
M.item("ossuary", KEY, ka, kb)
for t, da, db in (("SkullImmobile", 0.6, 0.6), ("ArmBoneImmobile", -0.6, 0.4), ("LegBoneImmobile", -0.1, -0.8),
                  ("Longsword", 0.8, -0.6)):
    M.put("ossuary", t, ka + da, kb + db, clear=2.4)
# potions where a player stops between stages: the library after the way down, the coven's stores, the crypt after
# the runes, the mausoleum before the beams
for rid, n in (("library", 2), ("coven", 3), ("crypt", 2), ("mausoleum", 1)):
    w, h = M.rooms[rid]["size"]
    pa, pb = free_spot(M, rid, 2.0, 2.0, clear=1.2)
    for k in range(n):
        M.put(rid, "RedPotion", pa + 0.45 * k, pb, clear=2.4)
w, h = M.rooms["coven"]["size"]
M.put("coven", "CryptChest4", w / 2, h - 1.3, clear=2.4,
      items=["BluePotion", "CurePoisonPotion", ("Gold", {"Amount": 150})])
ingrid = M.person("camp", "War01A", "Evelyn", "Ingrid", pic="IngridPic", title="Ingrid")

# ---- the story --------------------------------------------------------------------------------------------------
q = M.q
MAIN, SIDE = "idol", "hagen"
J_MAIN = "Bring the Blue Idol up from the Vault of Night."
J_SIDE = "Find out what became of Hagen in the ossuary."
q.talker(ingrid, [
    q.say("Thanks again! The dead will sleep easier now.", when=q.at(MAIN, 3)),
    q.say("The Blue Idol! You did it! Vael is dust and the Lich's Hall stays shut. Here's your reward -- 600 in gold!",
          when=q.at(MAIN, 2, has=IDOL),
          do=[A.take(IDOL), A.gold(600), A.stage(MAIN, 3), q.done(J_MAIN)]),
    q.say("Hagen's key... So the dead got him after all. Poor fool. Take his amulet. It will keep you on your feet "
          "down there.",
          when=q.when(has=KEY, not_=f"{SIDE}done"),
          do=[A.take(KEY), A.give("AmuletofNature"), A.flag(f"{SIDE}done"), q.done(J_SIDE)]),
    q.say("Keep your voice down, stranger! The dead hear better than you think.\n\n"
          "An archmage called Vael the Unbound has broken into the Vault of Night. He wants the Blue Idol, one of the "
          "two keys to the Lich's Hall. The Necromancers sealed it in the vault at the bottom, beneath their beams. "
          "My partner Hagen went into the ossuary yesterday and never came out. Will you go down and bring me the Idol "
          "before Vael can use it?",
          when=q.at(MAIN, 0), ask=True,
          do=[A.stage(MAIN, 1), q.journal(J_MAIN), q.journal(J_SIDE)],
          else_=[q.tell(ingrid, "Then stay out of my way. I have no use for cowards.")]),
    q.say("Vael still lives. I can feel it in the walls.", when=q.at(MAIN, 1, has=IDOL)),
    q.say("Why are you still here? Vael won't wait for you!", when=q.at(MAIN, 1)),
], pic="IngridPic", title="Ingrid")
q.on_pickup(KEY, [q.journal("Hagen is dead. Bring his silver key back to Ingrid.")])
q.on_death(boss, [A.stage(MAIN, 2), q.note("Vael the Unbound is dead. The vault beyond his hall lies open.")])
q.start([q.journal("Speak to Ingrid at the camp by the upper gate.")])
M.sign("camp", "THE VAULT OF NIGHT. The dead keep what lies below.", 2.0, 1.4)

m = M.m                                   # tests/server_smoke.py reads the spec as m
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out", "trapdemo", NAME)
if cleared: print(f"{NAME}: cleared from the passages' mouths: {', '.join(cleared)}")
M.finish(None if out == "-" else out)
