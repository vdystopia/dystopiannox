"""TrapLab: one map per kind of trap (kit/trapkit: spike, flame, block, push, arrow, pit, blade, sentry, spell,
trigger), ten stations each, TL-<KIND>-01 to -10, from the plainest to the hardest (rules/TRAPS.md).

The map: a long hall (the hub) with a healing well and potions at its west end; the ten stations open off its
north-east side, each a walled run you cross from the hall to a small end room, with its sign at the mouth (label,
name, tier) and a portal in the end room back to the hall. Pits drop you into a sealed pit room with a portal back.
No monsters: the labs are for the traps alone (the gauntlets mix in monsters).

    py mapgen/designs/traplab.py <kind> [out_dir|-]        (kinds: kit/trapkit KINDS)
    py mapgen/designs/traplab.py all [out_dir]

Maps are named TL<Kind> (9 characters at most): TLSpike, TLFlame, TLBlock, TLPush, TLArrow, TLPit, TLBlade,
TLSentry, TLSpell, TLTrigger.
"""
import json, os, random, sys, zlib
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from nox import Spec, SOLO
from kit.dungeon import Dungeon
from kit.traps import Traps
from kit.trapkit import Station, PATTERNS, KINDS, TITLES
from kit.transport import Transporters
from kit.signs import wrap

HERE = os.path.dirname(os.path.abspath(__file__))
# walls and floors per lab, from Westwood's trap maps (G_Crypts, G_Lava, G_Castle, G_Temple, Con10a, Wiz09c)
STYLE = {
    "spike": ("DungeonStone", "GreenBrick", "CryptFloor"),
    "flame": ("GalavaTownWall", "LOTDPitted", "GalavaBrick2"),
    "block": ("DungeonStone", "CryptFloor", "GreenBrick"),
    "push": ("BrickBlue", "TileDark", "DungeonStoneDark"),
    "arrow": ("IxTempleWall", "IxBrickFancy", "AncientRuin"),
    "pit": ("CaveWall", "CaveHardBrown", "CaveHardTan"),
    "blade": ("DungeonStone", "DungeonStoneMuddy", "GreenBrick"),
    "sentry": ("LOTDBrick", "LOTDPitted", "LOTDBlackMarble"),
    "spell": ("StoneBlue", "TileDark", "RedBrick6"),
    "trigger": ("AncientRuin", "AncientRuinRough", "IxBrickFancy"),
}
NAMES = {k: "TL" + k.capitalize() for k in KINDS}
HUB_I0, HUB_J0, HUB_W = 64, -6, 6               # the hall: i from HUB_I0, j from HUB_J0, 6 squares wide
GAP = 4                                          # squares of wall between stations


def build(kind, out_dir=None):
    name = NAMES[kind]
    rng = random.Random(zlib.crc32(name.encode()))
    wall, floor, floor2 = STYLE[kind]
    m = Spec(name, summary=f"TrapLab: {TITLES[kind]}",
             description=f"[env:castle] TrapLab {TITLES[kind].lower()}: ten trap stations TL-{kind.upper()}-01 to "
                         f"-10, from the plainest to the hardest. Generated by Claude.",
             author="vdystopia (generated by Claude)", version="0.1", date="2026", type=SOLO, minPlayers=1, maxPlayers=1)
    m.d["nxz"] = False
    m.d["ambient"] = [175, 170, 165]
    m.loot = False
    TEXT = {}

    def text(key, s):
        k = f"{name}:{key}"
        assert len(k) <= 31, k
        TEXT[k] = s
        return k

    def sign(key, s, x, y, step=(0, -18)):
        for k, part in enumerate(wrap(s)):
            m.obj_px("Sign1", x + step[0] * k, y + step[1] * k, xfer={"Text": text(key if not k else f"{key}_{k + 1}", part)})

    pats = PATTERNS[kind]
    assert len(pats) == 10, (kind, len(pats))
    sizes = [p.size for p in pats]
    hub_len = sum(w for _, w in sizes) + GAP * (len(sizes) + 1) + 8
    d = Dungeon(m, rng, wall=wall, floor=floor)
    hub = d.box("hub", HUB_I0, HUB_J0, hub_len, HUB_W, floor=floor2)
    pit = d.box("pitroom", HUB_I0, HUB_J0 - 22, 10, 8, floor="DirtDark2", wall=wall)
    T = Traps(m, prefix="")
    tp = Transporters(m)
    m.transporters = tp
    stations = []
    i = HUB_I0 + 8 + GAP
    parts = []
    for k, p in enumerate(pats):
        L, W = p.size
        part = d.box(f"st{k}", i, HUB_J0 + HUB_W, L, W, axis="j", floor=floor)
        end = d.box(f"end{k}", i - 1, HUB_J0 + HUB_W + L, 5, W + 2, axis="j", floor=floor2)
        parts.append((p, part, end))
        i += W + GAP
    d.apply()
    fall = pit.at(5, 4)
    for k, (p, part, end) in enumerate(parts):
        label = f"TL-{kind.upper()}-{k + 1:02d}"
        st = Station(T, part, f"S{k + 1:02d}", rng, fall_to=fall, spec=m)
        meta = p(st)
        tier = meta.get("tier", p.tier)
        # the sign at the mouth, in the hall
        mx, my = hub.at(part.i0 - hub.i0 + part.width / 2, HUB_W - 1.2)
        sign(f"S{k + 1:02d}", f"{label} {p.title.upper()} ({tier}). {meta.get('tells', '')}", mx - 60, my + 20,
             step=(14, 14))
        # potions at the station's way in, the end room's sign and its portal back to the hall
        for q in range(2):
            m.obj_px("RedPotion", *part.at(0.8, 0.6 + 0.6 * q))
        ex, ey = end.at(2.5, (part.width + 2) / 2)
        sign(f"E{k + 1:02d}", f"{label} PASSED. Step on the pentagram to go back to the hall.", *end.at(1.0, 1.0))
        tp.add("portal", end.at(3.5, (part.width + 2) / 2), hub.at(part.i0 - hub.i0 + part.width / 2, 2.0),
               f"Back{k + 1:02d}", two_way=False)
        T.label(label, p.title, [*part.at(0, 0), *part.at(part.length, part.width)], kind, tier,
                notes=json.dumps(meta))
        stations.append(dict(label=label, title=p.title, tier=tier, meta=meta, L=part.length, W=part.width,
                             start=list(part.at(0.5, part.width / 2)), end=list(part.at(part.length, part.width / 2)),
                             along=list(part.direction()), across=list(part.across()), clocks=st.starts,
                             rest=st.rest))
    # the hall's west end: the start, a healing well, potions, the lab's sign
    m.obj_px("PlayerStart", *hub.at(3.0, HUB_W / 2))
    m.obj_px("WishingWell", *hub.at(5.5, 1.3))
    for q in range(4):
        m.obj_px("RedPotion", *hub.at(2.0 + 0.6 * q, HUB_W - 0.8))
    sign("Intro", f"TRAPLAB: {TITLES[kind].upper()}. Ten stations off this hall, TL-{kind.upper()}-01 to -10, "
         f"plainest first. Each sign names its trap; rate each by its label.", *hub.at(4.0, HUB_W - 1.0),
         step=(14, 14))
    # the pit room: fallers land here; a portal back to the hall's start
    sign("Pit", "You fell. The pentagram leads back to the hall.", *pit.at(2, 1.5))
    tp.add("portal", pit.at(8, 4), hub.at(4.0, 2.0), "PitBack", two_way=False)
    for o in m.d["objects"]:                          # every pit and crumbling floor drops into the pit room
        if o["type"] in ("Pit", "PitCrumblingFloor", "ForestPit"):
            o.setdefault("xfer", {}).update(FallX=int(fall[0]), FallY=int(fall[1]))
    T.attach()
    info = dict(name=name, kind=kind, stations=stations, hub_start=list(hub.at(3.0, HUB_W / 2)), pit=list(fall),
                walls=sorted(m.wallmap),         # every wall cell: the simulator blocks the pillars inside stations
                secret={f"{x},{y}": w["secret"] for (x, y), w in m.wallmap.items() if w.get("secret")})
    if out_dir and out_dir != "-":
        os.makedirs(out_dir, exist_ok=True)
        with open(os.path.join(out_dir, f"{name}.strings.json"), "w", encoding="utf-8") as f:
            json.dump(TEXT, f, ensure_ascii=False, indent=1)
        lines = m.build(out_dir)
        T.write(out_dir)
        with open(os.path.join(out_dir, f"{name}.lab.json"), "w", encoding="utf-8") as f:
            json.dump(info, f, indent=1)
        print("\n".join(l for l in lines if l.startswith(("OK", "ERROR", "CHECK", "SCRIPTS"))))
    print(f"{name}: {len(stations)} stations, {len(T.objects)} trap objects, {len(T.clocks)} clocks, "
          f"{len(T.movers)} movers, {len(T.zones)} zones")
    return m, info, T


if __name__ == "__main__":
    arg = sys.argv[1] if len(sys.argv) > 1 else "spike"
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", "out", "traplab")
    for kd in (KINDS if arg == "all" else [arg]):
        if kd in PATTERNS:
            build(kd, None if out == "-" else os.path.join(out, NAMES[kd]))
