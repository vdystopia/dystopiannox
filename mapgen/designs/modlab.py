"""ModLab: creative additions to the base game, laid out to try one by one (dystopiannox/mods/MODLAB.md;
scripts: kit/behaviours/mods.go, wired by kit/mods.py). Every feature has a sign with its ID.

- the armoury (west end of the long gallery, by the start): the power weapons on the floor, a row per weapon with
  its sign at the row's west end and its tiers or variants left to right (QA round 1: the Flamebrand's three variants
  W1, W1B, W1C in small, medium and large; the Chakram Storm, Bloodthirst and Frostbite in tiers 1-3), and two
  signs (SP1) on how the Spirit class plays;
- the training yard (middle of the gallery, T1): creatures that wait frozen until you come near or strike them,
  and come back six seconds after they die, to try the weapons on;
- five pens along the north side of the gallery, M1-M5: a new monster in each, frozen until you step into its pen,
  back twenty seconds after it dies;
- the forge (south of the armoury, S1): an anvil, the forge plate (the grey stone patch), the smith, gold, and
  spare weapons to work or melt down. A sealed vault east of everything holds the forged copies the anvil hands out,
  and a sealed test cell is where the self-test runs on a dedicated server.

    py mapgen/designs/modlab.py [out_dir|-]
"""
import json, os, random, re, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from nox import Spec, SOLO, px, uv_to_xy
from kit.npcs import Population
from kit.mods import Mods, WEAPONS, MONSTERS

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "ModLab"
rng = random.Random(7)
m = Spec(NAME, summary="Mod lab", description="[env:castle] Power weapons, new monsters and a smithing forge. "
         "Generated by Claude.", author="vdystopia (generated by Claude)", version="0.1", date="2026",
         type=SOLO, minPlayers=1, maxPlayers=1)
m.d["nxz"] = False
m.d["ambient"] = [200, 195, 190]
m.loot = False
P = lambda u, v: px(u, v)
TEXT = {}


def text(key, s):
    k = f"{NAME}:{key}"
    assert len(k) <= 31, k
    TEXT[k] = s
    return k


def sign(key, s, u, v, kind="Sign1", step=(0, -3)):
    """A small sign, or a short row of them: a sign prints its text on one line and a long one crashes the client
    (QA round 1, M2: the Giant Crab's sign, 274 characters, crashed the game to the desktop; kit/signs.py). A text past
    SIGN_WARN characters is cut at its sentences onto signs `step` uv units apart, "W1 (2 of 3): ..." on the next."""
    from kit.signs import wrap, SIGN_WARN
    parts = wrap(s)
    for k, part in enumerate(parts):
        assert len(part) <= SIGN_WARN, (key, part)
        m.obj_px(kind, *P(u + step[0] * k, v + step[1] * k), xfer={"Text": text(key if not k else f"{key}_{k + 1}", part)})


def gate(u_mid, v):
    """A three-cell opening in the wall line at v (rect walls run along u in steps of 2)."""
    for u in (u_mid - 2, u_mid, u_mid + 2):
        m.remove_wall(*(int(c) for c in uv_to_xy(u, v)))


def weapon(t, u, v):
    return m.obj_px(t, *P(u, v))


# ---- the rooms ------------------------------------------------------------------------------------------------
m.room(200, 380, -20, 20, wall="BrickPlain", floor="CobbleStone")            # the long gallery
PEN_FLOORS = ["DirtLight2", "DirtHard", "LOTDPitted", "VolcanicCraggy", "TileDark"]
for k in range(5):                                                              # five pens on its north side
    m.room(200 + 36 * k, 236 + 36 * k, 20, 56, wall="BrickPlain", floor=PEN_FLOORS[k])
    gate(218 + 36 * k, 20)
m.room(200, 260, -56, -20, wall="BrickPlain", floor="DirtDark2")               # the forge, south of the armoury
gate(230, -20)

for u, v in ((204, 16), (204, -16), (300, 16), (300, -16), (376, 16), (376, -16), (204, -52), (256, -52)):
    m.obj_px("TorchPole", *P(u, v))

pop = Population(m, rng)
mods = Mods(m, pop)
mods.test_cell(400, -48)                                                        # sealed: the self-test's stand-ins

# ---- the armoury: W1-W6 --------------------------------------------------------------------------------------
# One row per weapon family (QA round 1: W1 in three variants, the tiers of W2, W5 and W6), its sign at the west
# end of the row (a long text runs on westward onto a second sign), its tiers lying left to right (u 217, 222, 227)
# in the order the sign gives.
sign("Welcome", "MODLAB: creative additions to Nox. Armoury here: a row per weapon, its sign at the west end, its "
     "tiers left to right. Training yard east (T1), monster pens north (M1-M5), the forge south (S1).", 207, -6)
ARMOURY = [("W1", (0, 2, 3)), ("W1B", (0, 2, 3)), ("W1C", (0, 2, 3)), ("W2", (1, 2, 3)), ("W3", (0,)), ("W4", (0,)),
           ("W5", (1, 2, 3)), ("W6", (1, 2, 3))]
for k, (wid, tiers) in enumerate(ARMOURY):
    v = -17 + 4.4 * k
    order = {3: "small, medium, large"}.get(len(tiers)) if wid.startswith("W1") else "tiers 1, 2, 3"
    sign(wid, WEAPONS[wid]["text"] + (f" Here, left to right: {order}." if len(tiers) > 1 else ""), 212, v,
         step=(-3, 0))
    for j, tier in enumerate(tiers):
        stem = WEAPONS[wid]["name"].replace(" ", "")
        # the first W1 and W3 keep the names the forge's lines start from (mods.forge tier0 below)
        name = {("W1", 0): "W1_Flamebrand", ("W3", 0): "W3_QuakeHammer"}.get((wid, tier), f"{wid}_{stem}_T{tier}")
        mods.weapon(wid, *P(217 + 5 * j, v), tier=tier, name=name)
# a chest of spares by the door: a second Chakram Storm and Bloodthirst, and potions (power weapons work from chests)
m.obj_px("Chest4", *P(204, 12), items=[mods.weapon_item("W2", tier=2), mods.weapon_item("W5", tier=1), "RedPotion",
                                       "RedPotion", "RedPotion", "BluePotion"])
# SP1: the Spirit class is an engine mod (mods/engine/SPIRIT.md), not part of this map; two signs say how it plays
sign("SP1a", "SP1 THE MYSTIC (Spirit class). Play opennox-spirit-hd.exe and pick the class once called Conjurer. Its "
     "magic is Spirit, the cyan bar, not mana. Spirit refills three times slower than mana.", 203, -11)
sign("SP1b", "SP1 HOW SPIRIT FILLS. Half the damage of every blow you land with staff, bow or fist becomes Spirit. "
     "Mana crystals give none; blue potions still do. Fight close to keep casting.", 203, -15)

# ---- the training yard: T1 -----------------------------------------------------------------------------------
sign("T1", "T1 TRAINING YARD\nTry the weapons here. The creatures wait until you come near or strike them, and "
     "come back six seconds after they die.", 244, -14)
for k, (t, u, v) in enumerate((("GruntAxe", 262, -10), ("GruntAxe", 262, 10), ("Bear", 274, -4),
                               ("OgreBrute", 286, 8), ("Urchin", 286, -12), ("GruntAxe", 296, 0))):
    mods.trainee(t, *P(u, v), name=f"T1_Target{k + 1}", face=P(206, 0))

# ---- the pens: M1-M5 -----------------------------------------------------------------------------------------
for k, mid in enumerate(MONSTERS):                                              # M1-M5, one to a pen
    mid_u = 218 + 36 * k
    mods.monster(mid, *P(mid_u, 40), name=f"{mid}_{MONSTERS[mid]['name'][4:].replace(' ', '')}", wait=230.0,
                 respawn=20.0, face=P(mid_u, 20))
    sign(mid, MONSTERS[mid]["text"], mid_u + 5, 15, step=(4, 0))

# ---- the forge: S1 -------------------------------------------------------------------------------------------
# the forge explained where it is used (QA round 1, S1: "I'm not sure how this works"): one short sign at each part
sign("S1", "S1 THE FORGE: lay a weapon by the anvil, then step onto the grey stone patch beside this sign.", 241, -31)
sign("S1Tiers", "S1: a longsword, battle axe, Flamebrand (W1) or Warp Hammer (W3) is raised to fine, superb, then "
     "masterwork.", 246, -36)
sign("S1Price", "S1: a tier costs 100, 200 then 400 gold. Any other weapon laid by the anvil is melted down for 20 gold.",
     236, -45)
sign("S1Smith", "S1: each piece raises the smith's level. Tier N needs level N; each level takes 8% off. Ask him his level.",
     225, -37)
sign("S1Gold", "S1: gold for the forge lies in the west corner; spare weapons by the far wall.", 212, -44)
mods.forge(anvil=P(230, -40), smith=P(228, -42), plate=P(237, -36), vault_uv=(400, -12),
           tier0={"flamebrand": ["W1_Flamebrand"], "quake": ["W3_QuakeHammer"]})
m.obj_px("Bellows1", *P(222, -53))
for k in range(6):                                                    # 1,800 gold in the west corner
    m.obj_px("Gold", *P(205 + 3 * (k % 3), -48 - 4 * (k // 3)), xfer={"Amount": 300})
for k, t in enumerate(("Longsword", "Longsword", "BattleAxe", "BattleAxe")):   # spare weapons to work
    weapon(t, 252, -52 + 5 * k)
# and to melt down (no Staff: the editor draws it as a flat brown square, which the QA pictures showed as a pressure
# plate that is not in the game: QA round 1, S1)
for k, t in enumerate(("Sword", "Sword", "Sword", "MorningStar", "OgreAxe")):
    weapon(t, 246 + 3 * (k % 3), -27 - 3 * (k // 3))

m.obj_px("PlayerStart", *P(206, 0))
mods.attach()

out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out")
if out_dir != "-":
    os.makedirs(out_dir, exist_ok=True)       # the text first: the build's checker reads the signs' text beside the map
    with open(os.path.join(out_dir, f"{NAME}.strings.json"), "w", encoding="utf-8") as f:
        json.dump(TEXT, f, ensure_ascii=False, indent=1)
    lines = m.build(out_dir)
    print("\n".join(l for l in lines if l.startswith(("OK", "ERROR", "CHECK", "SCRIPTS"))))
print(f"creatures {len(pop.placed)} | signs {len(TEXT)} | mod calls {len(mods.calls)}")
